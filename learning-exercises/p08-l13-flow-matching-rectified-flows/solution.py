"""
Flow matching и rectified flows — эталон.

Открывай ПОСЛЕ своих зелёных тестов.
"""

import math


def interpolate(x0, x1, t):
    """Точка прямолинейного пути между данными x0 (t=0) и шумом x1 (t=1).

    interpolate(2.0, -1.0, 0.0)  ->  2.0    t=0 — это чистые ДАННЫЕ
    interpolate(2.0, -1.0, 1.0)  -> -1.0    t=1 — это чистый ШУМ
    interpolate(2.0, -1.0, 0.5)  ->  0.5    ровно посередине

    Формула flow matching: x_t = t * x1 + (1 - t) * x0.

    Ловушка направления времени: у DDPM t=0 — данные, t=T — шум, а шкала
    другая. Статьи путают это постоянно. Здесь t=0 — данные, t=1 — шум.
    """
    # одна строка вместо x0 + t * (x1 - x0): обе формы алгебраически
    # равны, но эта буквально повторяет запись из статьи Lipman 2023
    return t * x1 + (1 - t) * x0


def flow_target(x0, x1):
    """Целевая скорость на прямолинейном пути: производная x_t по времени.

    flow_target(2.0, -1.0)  -> -3.0
    flow_target(0.0,  5.0)  ->  5.0

    Путь прямой, значит его производная ПОСТОЯННА и от t не зависит вовсе.
    Именно поэтому обучение «simulation-free»: разворачивать ОДУ не нужно,
    цель известна сразу по паре (x0, x1).
    """
    return x1 - x0


def flow_matching_loss(velocity, x0s, x1s, ts):
    """Средний квадрат ошибки поля скоростей на тройках (x0, x1, t).

    Для каждой тройки: подставить x_t = interpolate(x0, x1, t) в velocity
    и сравнить с flow_target(x0, x1).

    v = lambda x, t: 2.0
    flow_matching_loss(v, [1.0], [3.0], [0.5])  ->  0.0   поле угадало
    flow_matching_loss(v, [1.0], [5.0], [0.5])  ->  4.0   (2 - 4)^2

    velocity — функция двух аргументов (x, t). На вход ей идёт именно x_t,
    а не x0 и не x1: модель во время сэмплирования видит только точку пути.
    Пустой набор троек даёт 0.0, а не деление на ноль.
    """
    n = len(ts)
    if n == 0:
        return 0.0
    total = 0.0
    for x0, x1, t in zip(x0s, x1s, ts):
        # цель считаем через flow_target, чтобы формула жила в одном месте
        diff = velocity(interpolate(x0, x1, t), t) - flow_target(x0, x1)
        total += diff * diff
    return total / n


def euler_sample(velocity, x1, num_steps):
    """Проинтегрировать поле скоростей от шума x1 (t=1) к данным (t=0).

    Шаг Эйлера назад по времени: x -= dt * velocity(x, t), dt = 1/num_steps.

    v = lambda x, t: 1.5
    euler_sample(v, 4.0, 1)   ->  2.5
    euler_sample(v, 4.0, 10)  ->  2.5    постоянное поле — шаги не важны

    Смысл всего урока: если путь ПРЯМОЙ, поле постоянно вдоль него, и один
    шаг Эйлера попадает в цель точно. Кривой путь так не берётся — там
    ошибка падает только с ростом num_steps.
    """
    x = x1
    dt = 1.0 / num_steps
    for i in range(num_steps):
        # t идёт 1, 1-dt, ... — значение ПЕРЕД шагом, как в явном Эйлере
        t = 1.0 - i * dt
        x -= dt * velocity(x, t)
    return x


def path_curvature(velocity, x1, num_steps):
    """Насколько траектория Эйлера отклоняется от прямой между её концами.

    Считаем максимум |x_i - хорда(t_i)| по всем узлам сетки, где хорда —
    прямая от (t=1, старт) до (t=0, финиш).

    path_curvature(lambda x, t: 2.0, 1.0, 10)  ->  0.0   постоянное поле
    path_curvature(lambda x, t: x,   1.0, 20)  ->  ~0.08 поле гнёт путь

    Ноль означает: одного шага Эйлера хватит. Отсюда и вся возня с reflow —
    выпрямить траектории, чтобы сэмплировать за 1-4 шага вместо 50.
    """
    dt = 1.0 / num_steps
    xs = [x1]
    ts = [1.0]
    x = x1
    for i in range(num_steps):
        t = 1.0 - i * dt
        x -= dt * velocity(x, t)
        xs.append(x)
        ts.append(1.0 - (i + 1) * dt)
    start, end = xs[0], xs[-1]
    # хорда параметризована временем: при t=1 даёт start, при t=0 — end
    worst = 0.0
    for xi, ti in zip(xs, ts):
        chord = end + ti * (start - end)
        worst = max(worst, abs(xi - chord))
    return worst


def reflow_pairs(velocity, noise_samples, num_steps):
    """Шаг reflow: связать каждый шум с той точкой, куда он приезжает по ОДУ.

    Вернуть список пар (x0, x1): x1 — исходный шум, x0 — результат
    интегрирования velocity из x1.

    v = lambda x, t: x
    reflow_pairs(v, [1.0], 100)  ->  [(0.366..., 1.0)]

    Порядок в паре — как в записи пути: сначала данные, потом шум.
    Пары «согласованы с ОДУ», поэтому прямая между ними уже почти совпадает
    с настоящей траекторией — вторая модель учится на выпрямленных путях.
    Цена: полный проход сэмплирования на каждую пару.
    """
    return [(euler_sample(velocity, x1, num_steps), x1) for x1 in noise_samples]


def logit_normal_t(rng, mean=0.0, std=1.0):
    """Сэмпл t из logit-normal: сигмоида от нормальной величины.

    Всегда лежит строго внутри (0, 1) и копит массу вокруг 0.5 — так делает
    SD3, потому что на средних t градиенты информативнее всего.

    logit_normal_t(random.Random(0))         ->  число из (0, 1), ~0.5
    logit_normal_t(rng, std=3.0)             ->  чаще у краёв 0 и 1

    rng — экземпляр random.Random, чтобы результат был воспроизводим.
    Ловушка: наивная 1/(1+exp(-z)) переполняется на больших |z|; при std=3
    такие z встречаются регулярно.
    """
    z = rng.gauss(mean, std)
    # ветвление ради устойчивости: exp(+большое) переполняется, exp(-большое)
    # спокойно уходит в ноль
    if z >= 0:
        return 1.0 / (1.0 + math.exp(-z))
    e = math.exp(z)
    return e / (1.0 + e)


def cfg_velocity(v_cond, v_uncond, w):
    """Classifier-free guidance для поля скоростей.

    cfg_velocity(2.0, 1.0, 0.0)  ->  2.0   w=0 — обычное условное поле
    cfg_velocity(2.0, 1.0, 1.0)  ->  3.0   шаг «прочь от безусловного»
    cfg_velocity(2.0, 2.0, 5.0)  ->  2.0   поля совпали — усиливать нечего

    Формула та же, что у диффузии, только вместо epsilon подставлена v:
    v_cfg = (1 + w) * v_cond - w * v_uncond.
    """
    return (1 + w) * v_cond - w * v_uncond
