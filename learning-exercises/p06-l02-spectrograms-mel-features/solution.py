"""
Спектрограммы, мел-шкала и признаки аудио — эталон.

Открывай ПОСЛЕ своих зелёных тестов.
"""

import math


def hann(n):
    """Окно Ханна длины n: список весов, которыми домножают кадр перед DFT.

    Формула: 0.5 * (1 - cos(2*pi*i / (n - 1))).

    hann(1)  ->  [1.0]                      (вырожденный случай, деления нет)
    hann(3)  ->  [0.0, 1.0, 0.0]
    hann(5)  ->  [0.0, 0.5, 1.0, 0.5, 0.0]

    Зачем: DFT считает, что кадр периодически повторяется. Если на краях
    кадра сигнал обрывается на ненулевом значении, в спектре появляется
    «размазня» (spectral leakage) — энергия чистого тона растекается по
    соседним бинам. Окно плавно гасит края до нуля и убирает разрыв.

    Ловушка: в знаменателе (n - 1), а не n. С n в знаменателе окно не
    доходит до нуля на правом краю. Это то же самое, что аргумент
    sym=True/False в scipy.signal.get_window.
    """
    if n == 1:
        return [1.0]
    return [0.5 * (1 - math.cos(2 * math.pi * i / (n - 1))) for i in range(n)]


def frame_signal(signal, frame_len, hop):
    """Нарезать сигнал на перекрывающиеся кадры длины frame_len с шагом hop.

    Возвращает список списков. Хвост, который не набирает полный кадр,
    отбрасывается — дополнять нулями здесь не надо.

    frame_signal([1, 2, 3, 4, 5], 3, 1)  ->  [[1,2,3], [2,3,4], [3,4,5]]
    frame_signal([1, 2, 3, 4], 2, 2)     ->  [[1,2], [3,4]]
    frame_signal([1, 2], 5, 1)           ->  []   (сигнал короче кадра)

    Число кадров: 1 + (len(signal) - frame_len) // hop, и это надо
    отдельно защитить от отрицательного значения.

    Зачем в AI: 25 мс окно с шагом 10 мс (400 и 160 отсчётов при 16 кГц) —
    стандарт ASR. 10-секундный клип даёт 998 кадров.
    """
    n = 1 + (len(signal) - frame_len) // hop
    if n <= 0:
        return []
    # срезы, а не копирование поэлементно: так и быстрее, и читается лучше
    return [signal[i * hop : i * hop + frame_len] for i in range(n)]


def rfft_magnitudes(frame):
    """Модули спектра вещественного кадра: n//2 + 1 бинов (от DC до Найквиста).

    Вторую половину спектра не считаем: у вещественного сигнала она
    зеркальна и новой информации не несёт. Ровно так же ведут себя
    numpy.fft.rfft и torch.fft.rfft.

    rfft_magnitudes([1, 1, 1, 1])   ->  [4.0, 0.0, 0.0]
    rfft_magnitudes([1, -1, 1, -1]) ->  [0.0, 0.0, 4.0]

    Бин 0 — это модуль суммы всех отсчётов (постоянная составляющая).

    Сложность O(n^2). Настоящая FFT делает то же за O(n log n), но здесь
    важно увидеть, что внутри — просто сумма синусов и косинусов.
    """
    N = len(frame)
    out = []
    for k in range(N // 2 + 1):
        re = 0.0
        im = 0.0
        for n, v in enumerate(frame):
            angle = -2 * math.pi * k * n / N
            re += v * math.cos(angle)
            im += v * math.sin(angle)
        out.append(math.hypot(re, im))
    return out


def stft_magnitude(signal, frame_len=400, hop=160):
    """STFT: матрица (n_frames, frame_len//2 + 1) модулей спектра.

    Порядок операций жёсткий: нарезать кадры -> домножить на окно Ханна
    -> посчитать спектр каждого кадра.

    len(stft_magnitude([0.0] * 1000, 64, 32))  ->  30
    len(stft_magnitude([0.0] * 1000, 64, 32)[0])  ->  33

    Ловушка: окно применяется к каждому кадру ОТДЕЛЬНО, уже после нарезки.
    Домножить весь сигнал на одно длинное окно — это не STFT.

    В бою это torch.stft / librosa.stft, и они делают ровно это, только
    векторизованно и через FFT.
    """
    win = hann(frame_len)
    frames = frame_signal(signal, frame_len, hop)
    return [rfft_magnitudes([w * s for w, s in zip(win, f)]) for f in frames]


def hz_to_mel(f):
    """Герцы в мелы: m = 2595 * log10(1 + f / 700).

    hz_to_mel(0)     ->  0.0
    hz_to_mel(700)   ->  781.17...   (мел ровно на границе «линейной» зоны)
    hz_to_mel(8000)  ->  2840.02...

    Зачем: человек слышит высоту логарифмически. Пара 100/200 Гц звучит
    «на таком же расстоянии», как 1000/2000 Гц. Мел-шкала выпрямляет это
    восприятие в линейную ось, и сеть получает признаки, где равные шаги
    равнозначны для уха.
    """
    return 2595.0 * math.log10(1.0 + f / 700.0)


def mel_to_hz(m):
    """Мелы обратно в герцы: f = 700 * (10^(m / 2595) - 1).

    mel_to_hz(0)        ->  0.0
    mel_to_hz(2840.02)  ->  примерно 8000.0

    Обратная к hz_to_mel — на этом свойстве её и проверяют тесты.
    """
    return 700.0 * (10 ** (m / 2595.0) - 1.0)


def mel_filterbank(n_mels, n_fft, sr, fmin=0.0, fmax=None):
    """Банк треугольных мел-фильтров: матрица (n_mels, n_fft//2 + 1).

    Строится так: берём n_mels + 2 точки, равномерно расставленные по
    МЕЛ-шкале между fmin и fmax, переводим их в герцы, герцы — в номера
    бинов DFT. Каждый фильтр m — треугольник, который поднимается от
    bins[m] до bins[m+1] и спадает от bins[m+1] до bins[m+2].

    len(mel_filterbank(4, 64, 16000))     ->  4
    len(mel_filterbank(4, 64, 16000)[0])  ->  33

    Ловушка: точки расставляются равномерно по мелам, а НЕ по герцам.
    Из-за этого верхние фильтры получаются широкими, а нижние узкими — это
    и есть логарифмическое восприятие в виде матрицы.

    Умножение спектра на эту матрицу — вся мел-спектрограмма целиком,
    в бою это один matmul (torchaudio.transforms.MelScale).
    """
    if fmax is None:
        fmax = sr / 2
    lo, hi = hz_to_mel(fmin), hz_to_mel(fmax)
    # n_mels + 2 точки: каждому фильтру нужны левый край, вершина и правый
    mels = [lo + (hi - lo) * i / (n_mels + 1) for i in range(n_mels + 2)]
    bins = [int(mel_to_hz(m) * n_fft / sr) for m in mels]

    n_bins = n_fft // 2 + 1
    fb = [[0.0] * n_bins for _ in range(n_mels)]
    for m in range(n_mels):
        left, peak, right = bins[m], bins[m + 1], bins[m + 2]
        # max(1, ...) в знаменателе: соседние точки могут схлопнуться в
        # один бин, и делить на ноль нельзя
        for k in range(left, min(peak, n_bins)):
            fb[m][k] = (k - left) / max(1, peak - left)
        for k in range(peak, min(right, n_bins)):
            fb[m][k] = (right - k) / max(1, right - peak)
    return fb


def log_mel_spectrogram(mag_frames, filterbank, eps=1e-10):
    """Лог-мел-спектрограмма: (n_frames, n_mels).

    Каждый кадр спектра проецируется на банк фильтров (взвешенная сумма
    бинов), затем берётся log от результата.

    На тишине (все модули нули) все значения равны log(eps).

    log_mel_spectrogram([[1.0, 1.0, 1.0]], [[1.0, 0.0, 0.0]])  ->  [[0.0]]

    Ловушка: log(0) — это -inf, который отравит и loss, и градиенты.
    Поэтому под логарифмом стоит max(value, eps), а не просто value.

    Это вход Whisper, Parakeet и SeamlessM4T. Универсальный аудио-фронтенд
    2026 года.
    """
    out = []
    for frame in mag_frames:
        # zip обрывается по короткому — фильтр и кадр обязаны совпадать по длине
        mels = [sum(w * v for w, v in zip(f, frame)) for f in filterbank]
        out.append([math.log(max(v, eps)) for v in mels])
    return out
