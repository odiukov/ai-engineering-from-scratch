"""
Отбор признаков — эталон.

Открывай ПОСЛЕ своих зелёных тестов.
"""

import math


def variance_threshold(X, threshold=0.01):
    """Фильтр по дисперсии. Вернуть (маска, список дисперсий по столбцам).

    variance_threshold([[1.0, 5.0], [3.0, 5.0]], 0.01)
        ->  ([True, False], [1.0, 0.0])

    Дисперсия по всей выборке (делим на n). В маске True — признак остаётся,
    то есть его дисперсия СТРОГО больше порога.

    Самый дешёвый фильтр из всех: он даже не смотрит на целевую переменную.
    И самый ограниченный — шум с огромной дисперсией он пропустит с радостью.
    """
    n = len(X)
    variances = []
    for j in range(len(X[0])):
        column = [row[j] for row in X]
        m = sum(column) / n
        variances.append(sum((x - m) ** 2 for x in column) / n)
    return [v > threshold for v in variances], variances


def correlation(a, b):
    """Корреляция Пирсона двух списков: число от -1 до 1.

    correlation([1, 2, 3], [2, 4, 6])    ->  1.0
    correlation([1, 2, 3], [3, 2, 1])    ->  -1.0
    correlation([1, 1, 1], [1, 2, 3])    ->  0.0

    Ловушка: у постоянного списка нулевое отклонение и знаменатель обнуляется.
    Договорённость — возвращать 0.0.

    Корреляция видит только линейную связь. Симметричная зависимость вроде
    "цель равна единице на краях диапазона" даёт ровно ноль — и признак,
    идеально предсказывающий цель, окажется выброшен. Против этого и нужна
    взаимная информация.
    """
    n = len(a)
    ma, mb = sum(a) / n, sum(b) / n
    cov = sum((x - ma) * (y - mb) for x, y in zip(a, b))
    va = sum((x - ma) ** 2 for x in a)
    vb = sum((y - mb) ** 2 for y in b)
    denom = math.sqrt(va * vb)
    return cov / denom if denom else 0.0


def discretize(values, n_bins=10):
    """Разложить непрерывные значения по n_bins равным корзинам. Вернуть индексы.

    discretize([1, 2, 3, 4], 2)  ->  [0, 0, 1, 1]
    discretize([5, 5, 5], 4)     ->  [0, 0, 0]

    Границы: n_bins+1 равномерных точек от минимума до максимума. Номер корзины
    — это сколько ВНУТРЕННИХ границ (без крайних) не превышают значение.
    Минимум попадает в корзину 0, максимум — в корзину n_bins-1.

    Ловушка: постоянный список даёт нулевую ширину корзины — верни нули.

    Число корзин — компромисс: мало корзин теряют структуру, много корзин
    дробят данные так, что в каждой корзине оказывается по одной точке,
    и оценка взаимной информации превращается в шум.
    """
    low, high = min(values), max(values)
    if low == high:
        return [0] * len(values)
    width = (high - low) / n_bins
    # внутренние границы: low+width, ..., high-width
    edges = [low + i * width for i in range(1, n_bins)]
    return [sum(1 for e in edges if e <= x) for x in values]


def mutual_information(X, y, n_bins=10):
    """Взаимная информация каждого признака с целью. Список длины числа столбцов.

    mutual_information([[0.0], [1.0], [0.0], [1.0]], [0, 1, 0, 1], 2)  ->  [log(2)]
    Независимый от цели признак даёт 0.0.

    I(X; Y) = сумма по парам p(x,y) * log(p(x,y) / (p(x) * p(y))), натуральный
    логарифм. Пары с нулевой вероятностью пропускаем: log(0) не существует,
    а вклад такой пары всё равно нулевой.

    Непрерывный признак сначала раскладывается по корзинам.

    В отличие от корреляции, взаимная информация ловит любую зависимость,
    включая нелинейную: ей всё равно, как связаны величины, важно лишь,
    что знание одной уменьшает неопределённость другой.
    """
    n = len(y)
    y_counts = {}
    for label in y:
        y_counts[label] = y_counts.get(label, 0) + 1

    scores = []
    for j in range(len(X[0])):
        binned = discretize([row[j] for row in X], n_bins)
        x_counts = {}
        joint = {}
        for b, label in zip(binned, y):
            x_counts[b] = x_counts.get(b, 0) + 1
            joint[(b, label)] = joint.get((b, label), 0) + 1
        # идём по фактически встреченным парам: нулевые всё равно не дают вклада
        mi = 0.0
        for (b, label), count in joint.items():
            p_xy = count / n
            p_x = x_counts[b] / n
            p_y = y_counts[label] / n
            mi += p_xy * math.log(p_xy / (p_x * p_y))
        scores.append(mi)
    return scores


def select_k_best(scores, k):
    """Индексы k признаков с наибольшими баллами, по возрастанию индекса.

    select_k_best([0.1, 0.9, 0.5], 2)  ->  [1, 2]
    select_k_best([1.0, 1.0, 0.0], 1)  ->  [0]

    При равных баллах побеждает меньший индекс — отбор обязан быть
    воспроизводимым, иначе два запуска дадут две разные модели.
    """
    # ключ (-балл, индекс): по убыванию балла, при ничьей по возрастанию индекса
    order = sorted(range(len(scores)), key=lambda i: (-scores[i], i))
    return sorted(order[:k])


def logistic_weights(X, y, alpha=0.0, lr=0.1, epochs=200):
    """Логистическая регрессия градиентным спуском. Вернуть (веса, смещение).

    Веса и смещение стартуют с нуля. На каждой эпохе:
        p = sigmoid(X @ w + b), ошибка = p - y,
        w -= lr * (X^T @ ошибка) / n,  b -= lr * среднее(ошибка)
    и, если alpha > 0, мягкий порог: w = знак(w) * max(|w| - lr*alpha, 0).

    logistic_weights([[-1.0], [1.0]], [0, 1])[0][0]  ->  положительное число

    Мягкий порог — это и есть L1: он не просто уменьшает вес, а обнуляет его
    ровно, если градиент не в силах перетащить его через порог. L2 так не умеет,
    он лишь бесконечно приближает вес к нулю.

    Ловушка: exp от большого отрицательного числа переполняется. Обрежь
    аргумент по модулю, скажем, до 500.
    """
    n = len(X)
    n_features = len(X[0])
    w = [0.0] * n_features
    b = 0.0
    for _ in range(epochs):
        errors = []
        for row, target in zip(X, y):
            z = sum(wj * xj for wj, xj in zip(w, row)) + b
            # обрезка: math.exp(1000) — это OverflowError, а не бесконечность
            z = max(-500.0, min(500.0, z))
            errors.append(1.0 / (1.0 + math.exp(-z)) - target)
        for j in range(n_features):
            grad = sum(e * row[j] for e, row in zip(errors, X)) / n
            w[j] -= lr * grad
            if alpha:
                shrunk = abs(w[j]) - lr * alpha
                w[j] = math.copysign(shrunk, w[j]) if shrunk > 0 else 0.0
        b -= lr * (sum(errors) / n)
    return w, b


def rfe(X, y, n_features_to_select, lr=0.1, epochs=200):
    """Рекурсивное исключение признаков. Вернуть (маска, ранги).

    Цикл: обучить модель на оставшихся признаках, выбросить признак с
    наименьшим модулем веса, повторить, пока не останется нужное число.

    Ранг 1 — признак отобран. Первый выброшенный получает ранг, равный общему
    числу признаков, следующий — на единицу меньше. Чем больше ранг, тем
    раньше признак признали бесполезным.

    rfe([[-1.0, 5.0], [1.0, 5.0]], [0, 1], 1)  ->  ([True, False], [1, 2])

    Ловушка: веса считаются заново на КАЖДОЙ итерации. Отранжировать один раз
    и срезать хвост — это уже не RFE, а фильтр: смысл метода в том, что после
    удаления признака важность остальных меняется.

    При равных модулях выбрасывается признак с меньшей позицией среди
    оставшихся — иначе результат не воспроизводится.
    """
    n_total = len(X[0])
    remaining = list(range(n_total))
    rankings = [1] * n_total
    rank = n_total
    while len(remaining) > n_features_to_select:
        subset = [[row[j] for j in remaining] for row in X]
        w, _ = logistic_weights(subset, y, 0.0, lr, epochs)
        weakest = min(range(len(w)), key=lambda i: (abs(w[i]), i))
        rankings[remaining[weakest]] = rank
        rank -= 1
        remaining.pop(weakest)
    return [r == 1 for r in rankings], rankings


def l1_select(X, y, alpha=0.5, lr=0.1, epochs=200):
    """Встроенный отбор через L1: маска признаков с ненулевым весом.

    l1_select([[-3.0, 5.0], [3.0, 5.0]], [0, 1])  ->  [True, False]

    Ненулевым считается вес с модулем больше 1e-6: после мягкого порога
    "почти ноль" — это ноль, но сравнивать float с нулём напрямую не стоит.

    Отличие от RFE: здесь одно обучение вместо N. Модель сама решает, кого
    выбросить, прямо во время подгонки. Плата — метод работает только для
    линейных моделей и не увидит нелинейную важность.

    Чем больше alpha, тем меньше признаков переживёт отбор — вплоть до нуля.
    """
    w, _ = logistic_weights(X, y, alpha, lr, epochs)
    return [abs(wj) > 1e-6 for wj in w]
