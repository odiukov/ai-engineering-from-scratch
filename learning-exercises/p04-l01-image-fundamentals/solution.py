"""
Основы изображений: пиксели, каналы, цветовые пространства — эталон.

Открывай ПОСЛЕ своих зелёных тестов.
"""


def hwc_to_chw(img):
    """Переложить изображение из HWC в CHW. Аналог np.transpose(img, (2, 0, 1)).

    hwc_to_chw([[[1, 2, 3], [4, 5, 6]]])  ->  [[[1, 4]], [[2, 5]], [[3, 6]]]

    На входе список H строк, в строке W пикселей, в пикселе C чисел.
    На выходе список C плоскостей, в плоскости H строк по W чисел.

    HWC — это диск, PIL, OpenCV. CHW — это PyTorch и cuDNN. Скормить сети
    HWC вместо CHW исключения не вызовет: первый conv просто примет высоту
    за канал и молча испортит метрики.

    Новые списки, а не ссылки на старые: иначе правка результата испортит
    исходное изображение.
    """
    h = len(img)
    w = len(img[0])
    c = len(img[0][0])
    return [[[img[i][j][k] for j in range(w)] for i in range(h)] for k in range(c)]


def chw_to_hwc(img):
    """Обратный переклад: CHW -> HWC. Аналог np.transpose(img, (1, 2, 0)).

    chw_to_hwc([[[1, 4]], [[2, 5]], [[3, 6]]])  ->  [[[1, 2, 3], [4, 5, 6]]]

    Проверка на себе: chw_to_hwc(hwc_to_chw(x)) обязано вернуть ровно x.
    Если не возвращает — перепутан порядок осей в одной из двух функций.
    """
    c = len(img)
    h = len(img[0])
    w = len(img[0][0])
    return [[[img[k][i][j] for k in range(c)] for j in range(w)] for i in range(h)]


def rgb_to_grayscale(img):
    """Яркость по ITU-R BT.601: Y = 0.299 R + 0.587 G + 0.114 B.

    На входе HWC-изображение, на выходе двумерная сетка чисел (H x W).

    rgb_to_grayscale([[[255, 0, 0]]])      ->  [[76.245]]
    rgb_to_grayscale([[[100, 100, 100]]])  ->  [[100.0]]

    Это НЕ среднее по каналам: у чистого красного среднее дало бы 85, а
    правильный ответ 76.245. Веса неравные, потому что глаз сильнее всего
    реагирует на зелёный. Сумма весов ровно 1.0, поэтому серый пиксель
    переходит сам в себя.

    Аналог cv2.cvtColor(img, cv2.COLOR_RGB2GRAY) и PIL .convert("L").
    """
    return [[0.299 * px[0] + 0.587 * px[1] + 0.114 * px[2] for px in row] for row in img]


def rgb_to_hsv(pixel):
    """Один пиксель (R, G, B) из [0, 255] в (H, S, V).

    H в градусах [0, 360), S и V в [0, 1].

    rgb_to_hsv((255, 0, 0))     ->  (0.0, 1.0, 1.0)
    rgb_to_hsv((0, 255, 0))     ->  (120.0, 1.0, 1.0)
    rgb_to_hsv((10, 10, 10))    ->  (0.0, 0.0, 0.0392...)

    Схема: перевести каналы в [0, 1], взять cmax, cmin, delta = cmax - cmin.
    V = cmax. S = delta / cmax (и 0, если cmax == 0). Оттенок зависит от
    того, какой канал оказался максимумом:
        max == R:  ((G - B) / delta) % 6
        max == G:  ((B - R) / delta) + 2
        max == B:  ((R - G) / delta) + 4
    результат умножить на 60.

    Ловушка: серый пиксель даёт delta == 0, и формулы делят на ноль.
    Такой случай разбирается отдельно: H = 0, S = 0.

    Смысл HSV в том, что оттенок не зависит от яркости: затемни картинку
    вдвое — H и S не сдвинутся, поедет только V. На этом держится вся
    классическая сегментация по цвету.
    """
    r, g, b = pixel[0] / 255.0, pixel[1] / 255.0, pixel[2] / 255.0
    cmax = max(r, g, b)
    cmin = min(r, g, b)
    delta = cmax - cmin

    if delta == 0:
        # серый: оттенка нет, насыщенности нет; делить на delta нельзя
        hue = 0.0
    elif cmax == r:
        hue = (((g - b) / delta) % 6) * 60.0
    elif cmax == g:
        hue = (((b - r) / delta) + 2) * 60.0
    else:
        hue = (((r - g) / delta) + 4) * 60.0

    sat = 0.0 if cmax == 0 else delta / cmax
    return (hue, sat, cmax)


def preprocess_imagenet(img, mean=(0.485, 0.456, 0.406), std=(0.229, 0.224, 0.225)):
    """HWC uint8 -> CHW float, стандартизованный под ImageNet.

    Три шага ровно в этом порядке:
      1. поделить на 255 — получаем [0, 1];
      2. вычесть mean и поделить на std своего канала;
      3. переложить HWC -> CHW.

    preprocess_imagenet([[[0, 0, 0]]])  ->  [[[-2.1179]], [[-2.0357]], [[-1.8044]]]

    Порядок принципиален: если стандартизовать после перекладки, то индекс
    канала придётся искать в другой оси, и легко вычесть mean красного из
    зелёного. Если забыть шаг 1, mean и std окажутся не в том масштабе.

    Ровно это делает пара torchvision transforms.ToTensor() +
    transforms.Normalize(mean, std). Подать модели сырой uint8 — самая
    частая молчаливая ошибка в прикладном CV.
    """
    scaled = [
        [[(px[k] / 255.0 - mean[k]) / std[k] for k in range(len(px))] for px in row]
        for row in img
    ]
    # перекладку не дублируем — она уже написана выше
    return hwc_to_chw(scaled)


def deprocess_imagenet(chw, mean=(0.485, 0.456, 0.406), std=(0.229, 0.224, 0.225)):
    """Обратное к preprocess_imagenet: CHW float -> HWC uint8.

    Шаги в обратном порядке: CHW -> HWC, умножить на std и прибавить mean,
    умножить на 255, ограничить диапазоном [0, 255], округлить до целого.

    deprocess_imagenet(preprocess_imagenet(img))  ->  ровно img

    Округление, а не отбрасывание дробной части: 76.9999999 обязано стать
    77, иначе на круговом прогоне вылезет ошибка в единицу на каждом
    втором пикселе.

    clip нужен потому, что после аугментаций значения выходят за границы —
    без него получится отрицательный «цвет».
    """
    hwc = chw_to_hwc(chw)
    out = []
    for row in hwc:
        new_row = []
        for px in row:
            new_row.append(
                [
                    min(255, max(0, int(round((px[k] * std[k] + mean[k]) * 255.0))))
                    for k in range(len(px))
                ]
            )
        out.append(new_row)
    return out


def resize_nearest(img, out_h, out_w):
    """Ресайз двумерной сетки методом ближайшего соседа.

    Отображение координат: src_i = int(i * H / out_h), так же по столбцам,
    с ограничением сверху H - 1 и W - 1.

    resize_nearest([[1, 2]], 1, 4)   ->  [[1, 1, 2, 2]]
    resize_nearest([[1, 2]], 1, 2)   ->  [[1, 2]]

    Никакой арифметики над значениями — только выбор существующего.
    Поэтому это единственный допустимый метод для масок сегментации и
    карт классов: интерполяция между id 3 и id 5 дала бы несуществующий
    класс 4.

    Аналог PIL Image.resize(..., Image.NEAREST).
    """
    h = len(img)
    w = len(img[0])
    out = []
    for i in range(out_h):
        si = min(h - 1, int(i * h / out_h))
        row = img[si]
        out.append([row[min(w - 1, int(j * w / out_w))] for j in range(out_w)])
    return out


def resize_bilinear(img, out_h, out_w):
    """Ресайз двумерной сетки билинейной интерполяцией.

    Отображение координат «по углам»: src_i = i * (H - 1) / (out_h - 1),
    а при out_h == 1 просто 0.0. Дальше берутся два соседних индекса
    i0 = floor(src_i), i1 = min(i0 + 1, H - 1) и вес wi = src_i - i0;
    то же самое по столбцам; итог — взвешенная сумма четырёх соседей.

    resize_bilinear([[0, 1, 2]], 1, 5)  ->  [[0.0, 0.5, 1.0, 1.5, 2.0]]
    resize_bilinear([[5, 5], [5, 5]], 3, 3)  ->  сетка 3x3 из пятёрок

    Такое отображение соответствует
    torch.nn.functional.interpolate(..., mode="bilinear", align_corners=True):
    углы исходной картинки попадают ровно в углы результата, и ресайз в тот
    же размер — тождество. У PIL отображение чуть другое (по центрам
    пикселей), поэтому числа с ним совпадут не до последнего знака.

    Ловушка: out_h == 1 или H == 1 — деление на ноль в формуле координат.
    """
    h = len(img)
    w = len(img[0])
    out = []
    for i in range(out_h):
        si = 0.0 if out_h == 1 else i * (h - 1) / (out_h - 1)
        i0 = int(si)
        i1 = min(i0 + 1, h - 1)
        wi = si - i0
        row = []
        for j in range(out_w):
            sj = 0.0 if out_w == 1 else j * (w - 1) / (out_w - 1)
            j0 = int(sj)
            j1 = min(j0 + 1, w - 1)
            wj = sj - j0
            # сначала интерполируем по строкам, потом между строками:
            # два прохода дешевле, чем четыре умножения на каждый пиксель
            top = img[i0][j0] * (1 - wj) + img[i0][j1] * wj
            bottom = img[i1][j0] * (1 - wj) + img[i1][j1] * wj
            row.append(top * (1 - wi) + bottom * wi)
        out.append(row)
    return out
