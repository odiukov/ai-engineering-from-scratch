"""
Нормы и расстояния — эталон.

Открывай ПОСЛЕ своих зелёных тестов.
"""

import math


def dot(a, b):
    """Скалярное произведение двух векторов.

    dot([1, 2, 3], [4, 5, 6])  ->  32
    dot([1, 0], [0, 1])        ->  0    (перпендикулярны)
    dot([3, 0], [1, 0])        ->  3    (а cos тех же векторов равен 1.0)

    Скалярное произведение равно ||a|| * ||b|| * cos(угол). То есть в нём
    сидит и направление, и обе длины. Векторные базы дают выбрать между ним
    и косинусом: dot ставит выше «популярные» длинные векторы, косинус —
    нет. На нормированных эмбеддингах разницы нет вообще.
    """
    return sum(x * y for x, y in zip(a, b))


def lp_norm(v, p=2):
    """Норма Lp: (sum |v_i|^p)^(1/p). Для p=inf — максимум модуля.

    lp_norm([3, 4])                ->  5.0    (обычная евклидова длина)
    lp_norm([1, -2, 3], 1)         ->  6.0    (манхэттенская)
    lp_norm([1, -2, 3], float('inf'))  ->  3.0    (чебышёвская)

    p меняет форму «единичного шара»: у p=1 это ромб с углами на осях, у
    p=2 круг, у p=inf квадрат. Углы ромба лежат на осях — поэтому L1 в
    регуляризации (Lasso) занулет веса, а гладкий круг L2 (Ridge) только
    сжимает их.

    Модуль обязателен: без него нечётные p дадут отрицательный вклад,
    а норма отрицательной не бывает.
    """
    if p == float("inf"):
        # предел Lp при p -> inf: остаётся только самая большая координата
        return max((abs(x) for x in v), default=0.0)
    return sum(abs(x) ** p for x in v) ** (1.0 / p)


def distance(a, b, p=2):
    """Расстояние между точками: норма их разности.

    distance([1, 2, 3], [4, 0, 6])          ->  4.69041575...  (L2)
    distance([1, 2, 3], [4, 0, 6], 1)       ->  8.0            (L1)
    distance([1, 2, 3], [4, 0, 6], float('inf'))  ->  3.0      (L-inf)

    Любое расстояние между векторами — это ||a - b||. Отсюда и правило
    L_inf <= L2 <= L1: чем больше p, тем сильнее доминирует самая крупная
    координата и тем меньше вклад остальных.

    MAE — это среднее L1 между предсказанием и целью, MSE — среднее
    квадрата L2. Отсюда и разная чувствительность к выбросам.
    """
    return lp_norm([x - y for x, y in zip(a, b)], p)


def cosine_similarity(a, b):
    """Косинус угла между векторами: от -1 до 1. Длины не важны.

    cosine_similarity([1, 0], [1, 1])   ->  0.70710678...
    cosine_similarity([1, 0], [5, 0])   ->  1.0    (то же направление)
    cosine_similarity([1, 0], [0, 1])   ->  0.0    (перпендикулярны)
    cosine_similarity([1, 0], [-1, 0])  ->  -1.0   (противоположны)

    Формула: dot(a, b) / (||a|| * ||b||). Нормировка выкидывает длины, и
    остаётся только направление. Поэтому косинус правит в NLP: документ
    вдвое длиннее — то же распределение слов, тот же смысл, тот же вектор
    по направлению.

    Ловушка: нулевой вектор. Его длина ноль, делить не на что, угла у него
    нет. Договоримся возвращать 0.0.
    """
    na, nb = lp_norm(a, 2), lp_norm(b, 2)
    if na == 0.0 or nb == 0.0:
        return 0.0
    return dot(a, b) / (na * nb)


def mahalanobis(x, y, inv_cov):
    """Расстояние Махаланобиса: L2 в «отбелённом» пространстве.

    mahalanobis([0, 0], [3, 4], [[1, 0], [0, 1]])  ->  5.0  (как обычная L2)
    mahalanobis([0, 0], [4, 0], [[0.25, 0], [0, 1]])  ->  2.0

    Формула: sqrt(d^T * inv_cov * d), где d = x - y, а inv_cov — обратная
    ковариационная матрица данных (её сюда передают готовой).

    Смысл: евклидово расстояние считает все признаки одинаково важными и
    независимыми. Махаланобис сначала растягивает пространство так, чтобы
    признаки стали некоррелированными и единичной дисперсии, и только
    потом меряет. Рост 150 см при весе 80 кг далёк от среднего именно по
    Махаланобису, а по L2 — не особенно.

    Если inv_cov единичная, расстояние обязано совпасть с L2 — это
    хорошая проверка реализации.
    """
    d = [a - b for a, b in zip(x, y)]
    # сначала inv_cov @ d, потом d . (inv_cov @ d) — двойная свёртка
    right = [dot(row, d) for row in inv_cov]
    return math.sqrt(dot(d, right))


def jaccard_similarity(a, b):
    """Похожесть множеств: размер пересечения делить на размер объединения.

    jaccard_similarity({1, 2, 3}, {1, 3, 4, 5})  ->  0.4   (2 из 5)
    jaccard_similarity({1, 2}, {1, 2})           ->  1.0
    jaccard_similarity({1, 2}, {3, 4})           ->  0.0

    Работает там, где данные по природе множества, а не векторы: теги,
    категории, наборы слов без учёта частот. IoU в сегментации — это тот же
    Жаккар, только над множествами пикселей.

    Ловушка: два пустых множества. Объединение пусто, делить не на что.
    Считаем такие множества одинаковыми и возвращаем 1.0.
    """
    a, b = set(a), set(b)
    union = a | b
    if not union:
        return 1.0
    return len(a & b) / len(union)


def edit_distance(a, b):
    """Расстояние Левенштейна: минимум вставок, удалений и замен.

    edit_distance("kitten", "sitting")  ->  3
    edit_distance("abc", "abc")         ->  0
    edit_distance("", "abc")            ->  3

    Динамическое программирование: клетка (i, j) — это расстояние между
    первыми i символами a и первыми j символами b. Заполняется из трёх
    соседей: сверху (удаление), слева (вставка), по диагонали (замена или
    совпадение, если символы равны).

    Граница обязательна: превратить пустую строку в строку длины j стоит
    ровно j вставок.
    """
    previous = list(range(len(b) + 1))
    for i, ca in enumerate(a, start=1):
        # держим только предыдущую строку таблицы: память O(len(b)),
        # а не O(len(a) * len(b)) — сама таблица целиком не нужна
        current = [i]
        for j, cb in enumerate(b, start=1):
            current.append(
                min(
                    previous[j] + 1,  # удалить символ из a
                    current[j - 1] + 1,  # вставить символ из b
                    previous[j - 1] + (ca != cb),  # заменить (или ничего)
                )
            )
        previous = current
    return previous[-1]


def nearest_neighbor(query, points, metric):
    """Индекс ближайшей к query точки по заданной метрике.

    nearest_neighbor([1, 0], [[10, 0], [1, 1]], distance)  ->  1
    nearest_neighbor([1, 0], [[10, 0], [1, 1]],
                     lambda a, b: 1 - cosine_similarity(a, b))  ->  0

    metric — любая функция двух векторов, возвращающая число «чем больше,
    тем дальше». При равенстве побеждает меньший индекс.

    Два примера выше — это весь урок в двух строках: одни и те же данные,
    один и тот же запрос, разные ответы. Метрика — не деталь реализации,
    а определение слова «похоже».
    """
    best = None
    best_index = None
    for i, p in enumerate(points):
        d = metric(query, p)
        # строгое «меньше»: при равенстве остаётся тот, кого нашли раньше
        if best is None or d < best:
            best, best_index = d, i
    return best_index
