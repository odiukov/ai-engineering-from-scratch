"""
Производные и градиенты — эталон.

Открывай ПОСЛЕ своих зелёных тестов.
"""


def derivative(f, x, h=1e-5):
    """Численная производная функции одной переменной в точке x.

    derivative(lambda t: t * t, 3)   ->  6.0   (производная t^2 это 2t)
    derivative(lambda t: 5, 42)      ->  0.0   (константа не меняется)

    Используй ЦЕНТРАЛЬНУЮ разность: (f(x+h) - f(x-h)) / (2h).
    Односторонняя (f(x+h) - f(x)) / h тоже "работает", но её ошибка растёт
    как h, а у центральной — как h^2. На h=1e-5 это разница в точности
    в тысячи раз, и тесты это ловят.
    """
    return (f(x + h) - f(x - h)) / (2 * h)


def gradient(f, point, h=1e-5):
    """Градиент функции многих переменных: список частных производных.

    gradient(lambda p: p[0]**2 + p[1]**2, [3, 4])  ->  [6.0, 8.0]

    Частная производная по i-й координате — это обычная производная, когда
    все остальные координаты заморожены. Двигаем только i-ю на +-h.

    Градиент показывает направление самого быстрого РОСТА функции.
    """
    grad = []
    for i in range(len(point)):
        # копия на каждой итерации: править сам point нельзя, иначе
        # следующие координаты посчитаются от испорченной точки
        up, down = list(point), list(point)
        up[i] += h
        down[i] -= h
        grad.append((f(up) - f(down)) / (2 * h))
    return grad


def descent_step(point, grad, lr):
    """Один шаг градиентного спуска: сдвиг ПРОТИВ градиента.

    descent_step([3.0, 4.0], [6.0, 8.0], 0.1)  ->  [2.4, 3.2]

    Минус — принципиален. Градиент указывает вверх, а нам вниз.
    """
    return [p - lr * g for p, g in zip(point, grad)]


def minimize(f, start, lr=0.1, steps=100):
    """Градиентный спуск: из start скатиться в минимум f. Вернуть точку.

    minimize(lambda p: (p[0] - 5) ** 2, [0.0])  ->  примерно [5.0]

    Каждый шаг: посчитать градиент, шагнуть против него.
    """
    point = list(start)
    for _ in range(steps):
        point = descent_step(point, gradient(f, point), lr)
    return point


def is_close_to_minimum(f, point, tol=1e-3):
    """Похожа ли точка на минимум: все частные производные близки к нулю.

    is_close_to_minimum(lambda p: p[0]**2, [0.0])  ->  True
    is_close_to_minimum(lambda p: p[0]**2, [5.0])  ->  False

    Осторожно: нулевой градиент бывает и в максимуме, и в седле. Функция
    отвечает на вопрос "производная нулевая?", а не "это точно минимум?".
    """
    return all(abs(g) < tol for g in gradient(f, point))
