"""
Спекулятивное декодирование и EAGLE-3 — эталон.

Открывай ПОСЛЕ своих зелёных тестов.

Игрушечная модель урока: словарь из нескольких токенов, черновик выдаёт
распределение p, верификатор — q, оба одинаковы на каждой позиции. Этого
хватает, чтобы проверить главное свойство теоремы Leviathan: выход
спекулятивного цикла распределён РОВНО как q, а не «примерно как q».

Всё случайное берёт rng (random.Random) параметром. Глобальный random
внутри функций запрещён: тесты обязаны быть воспроизводимыми.
"""


def normalize(weights):
    """Неотрицательные веса -> распределение вероятностей.

    normalize([1.0, 3.0])   ->  [0.25, 0.75]
    normalize([2.0, 2.0])   ->  [0.5, 0.5]

    Любой отрицательный вес или неположительная сумма -> ValueError:
    вектор с отрицательной вероятностью не становится распределением,
    даже если его общая сумма положительна.
    """
    if any(w < 0 for w in weights):
        raise ValueError("веса должны быть неотрицательными")
    total = sum(weights)
    if total <= 0:
        raise ValueError(f"сумма весов должна быть положительной, получено {total}")
    return [w / total for w in weights]


def sample_index(dist, u):
    """Обратная функция распределения: индекс по числу u из [0, 1).

    sample_index([0.5, 0.5], 0.0)  ->  0
    sample_index([0.5, 0.5], 0.5)  ->  1
    sample_index([0.0, 1.0], 0.0)  ->  1   (нулевую вероятность не выдаём)

    Идём по накопленной сумме и берём ПЕРВЫЙ индекс, где она строго
    больше u. Строгое неравенство важно: иначе токен с нулевой
    вероятностью иногда выпадает, и вся математика теоремы ломается.

    Отдельная функция вместо random.choices — потому что так тест может
    подать конкретное u и проверить границу, а не гадать по выборке.
    """
    acc = 0.0
    for i, p in enumerate(dist):
        acc += p
        if acc > u:
            return i
    # сюда попадаем только из-за накопленной ошибки округления
    return len(dist) - 1


def accept(q_prob, p_prob, u):
    """Правило Leviathan: принять черновой токен с вероятностью min(1, q/p).

    accept(0.5, 0.2, 0.9)  ->  True   (q > p, принимаем всегда)
    accept(0.1, 0.5, 0.9)  ->  False  (q/p = 0.2, а u = 0.9)
    accept(0.1, 0.5, 0.1)  ->  True

    Ловушка: p_prob == 0 значит, что черновик сам не мог выдать этот
    токен. Такое случается только из-за округления — принимаем, деление
    на ноль здесь недопустимо.

    Из этого одного правила и residual ниже следует вся теорема:
    распределение выхода совпадает с q при любом качестве черновика.
    """
    if p_prob <= 0:
        return True
    return u < min(1.0, q_prob / p_prob)


def residual(q, p):
    """Распределение поправки при отказе: (q - p)_+, нормированное.

    residual([0.6, 0.4], [0.2, 0.8])  ->  [1.0, 0.0]
    residual([0.5, 0.5], [0.5, 0.5])  ->  [0.5, 0.5]

    Берём поэлементно max(0, q_i - p_i) и нормируем. Отрицательную часть
    обнуляем: там, где черновик уже перебрал вероятности, добавлять
    нечего.

    Ловушка: если p == q, вся разность нулевая и нормировать нечего.
    В этом случае возвращаем сам q — так формула остаётся определённой.
    """
    raw = [max(0.0, qi - pi) for qi, pi in zip(q, p)]
    if sum(raw) <= 0:
        return list(q)
    return normalize(raw)


def spec_step(p, q, n, rng):
    """Один спекулятивный шаг: n черновых токенов, одна проверка, выдача.

    Возвращает список выданных токенов длиной от 1 до n+1.
    Принято черновых токенов ровно len(результат) - 1.

    Порядок действий:
      1. Тянем черновой токен d из p, тянем u, применяем accept.
      2. Приняли — кладём d и идём дальше.
      3. Отказ на позиции j — кладём токен из residual(q, p) и ВЫХОДИМ:
         дальше черновик считал от неправильного префикса.
      4. Все n приняты — кладём бонусный токен прямо из q. Он бесплатный:
         верификатор уже посчитал q на позиции n+1.

    rng — random.Random. Каждый вызов rng.random() это один «бросок»;
    порядок бросков зафиксирован, иначе тест не воспроизвести.
    """
    emitted = []
    for _ in range(n):
        d = sample_index(p, rng.random())
        if accept(q[d], p[d], rng.random()):
            emitted.append(d)
        else:
            # откат KV-кэша: логическая длина обрезается сюда же
            emitted.append(sample_index(residual(q, p), rng.random()))
            return emitted
    emitted.append(sample_index(q, rng.random()))
    return emitted


def expected_emitted(alpha, n):
    """Сколько токенов в среднем даёт один проход верификатора.

    Формула урока: (1 - alpha^(n+1)) / (1 - alpha).

    expected_emitted(0.0, 5)  ->  1.0   (черновик всегда мимо — одна поправка)
    expected_emitted(0.8, 5)  ->  3.689...

    Ловушка: alpha == 1 обнуляет знаменатель. Идеальный черновик даёт
    ровно n+1 токенов — разбери этот случай отдельно, а не дели на ноль.

    alpha — та самая величина, ради которой EAGLE-3 и существует:
    с 0.6 до 0.9 при n=5 число токенов на проход растёт с 2.2 до 4.1.
    """
    if not 0.0 <= alpha <= 1.0:
        raise ValueError(f"alpha должна быть в [0, 1], получено {alpha}")
    if alpha == 1.0:
        return float(n + 1)
    return (1.0 - alpha ** (n + 1)) / (1.0 - alpha)


def time_per_token(alpha, n, c):
    """Стоимость одного выданного токена в «проходах верификатора».

    c = cost(черновик) / cost(верификатор). Один спекулятивный шаг стоит
    n*c (n маленьких проходов) + 1 (один большой), и даёт
    expected_emitted(alpha, n) токенов.

    time_per_token(0.0, 0, 0.05)  ->  1.0   (обычное декодирование)
    time_per_token(0.8, 5, 0.05)  ->  0.338...

    Значение меньше 1.0 и есть ускорение: 0.338 это 2.95x.
    """
    return (n * c + 1.0) / expected_emitted(alpha, n)


def best_draft_length(alpha, c, max_n=20):
    """Оптимальная длина черновика: n, минимизирующее time_per_token.

    best_draft_length(0.6, 0.05)  ->  4
    best_draft_length(0.8, 0.05)  ->  8

    Перебираем n от 1 до max_n. При равенстве выигрывает меньшее n:
    короткий черновик дешевле по памяти и проще откатывать.

    Форма кривой: сначала выигрыш от батчинга растёт быстрее, чем
    стоимость черновика, потом alpha^n съедает всё — отсюда минимум.
    """
    return min(range(1, max_n + 1), key=lambda n: (time_per_token(alpha, n, c), n))
