"""
Статистика для машинного обучения — эталон.

Открывай ПОСЛЕ своих зелёных тестов.
"""

import math
import random


def mean(values):
    """Среднее арифметическое непустого списка.

    mean([1, 2, 3, 4])       ->  2.5
    mean([1, 2, 3, 4, 1000]) ->  202.0

    Второй пример — вся беда среднего: один выброс утаскивает его куда
    угодно. Медиана тех же данных равна 3. Когда среднее и медиана
    расходятся, распределение перекошено, и отчитываться одним средним
    уже нечестно.
    """
    return sum(values) / len(values)


def percentile(values, q):
    """Перцентиль q (от 0 до 100) с линейной интерполяцией.

    percentile([1, 2, 3, 4], 50)   ->  2.5    (это же и медиана)
    percentile([1, 2, 3], 50)      ->  2.0
    percentile([1, 2, 3, 4], 0)    ->  1.0    (минимум)
    percentile([1, 2, 3, 4], 100)  ->  4.0    (максимум)

    Считается так: данные сортируются, позиция = q/100 * (n - 1). Если
    позиция дробная — линейно смешиваем два соседних значения.

    Отсюда берутся и медиана (q=50), и IQR (q=75 минус q=25), и вся
    латентностная отчётность: P50 — типичный пользователь, P99 — хвост,
    который обычно в разы хуже медианы.

    Ловушка: сортировать нужно КОПИЮ. Список вызывающего портить нельзя.
    """
    ordered = sorted(values)
    n = len(ordered)
    if n == 1:
        return float(ordered[0])
    position = (q / 100.0) * (n - 1)
    low = math.floor(position)
    high = math.ceil(position)
    if low == high:
        return float(ordered[low])
    # вес показывает, насколько позиция ушла от левого соседа к правому
    weight = position - low
    return ordered[low] + (ordered[high] - ordered[low]) * weight


def variance(values, sample=True):
    """Дисперсия. sample=True — выборочная (делим на n-1), иначе на n.

    variance([2, 4, 4, 4, 5, 5, 7, 9], sample=False)  ->  4.0
    variance([2, 4, 4, 4, 5, 5, 7, 9])                ->  4.571428571428571
    variance([7, 7, 7])                               ->  0.0

    Поправка Бесселя (n-1) существует потому, что отклонения считаются от
    ВЫБОРОЧНОГО среднего, а оно само подогнано под данные. Без поправки
    оценка систематически занижена. На тысячах точек разница неразличима,
    на десятке — заметна.

    Ловушка: выборочная дисперсия одного значения не определена — делить
    на ноль. Это ValueError, а не 0.0: молчаливый ноль здесь опаснее.
    """
    n = len(values)
    if sample and n < 2:
        raise ValueError("выборочная дисперсия требует минимум двух значений")
    m = mean(values)
    # центрируем один раз: (x - m)^2 устойчивее, чем E[x^2] - E[x]^2
    return sum((x - m) ** 2 for x in values) / (n - 1 if sample else n)


def pearson(x, y):
    """Корреляция Пирсона: сила ЛИНЕЙНОЙ связи, от -1 до 1.

    pearson([1, 2, 3], [2, 4, 6])   ->  1.0    (идеальная прямая)
    pearson([1, 2, 3], [3, 2, 1])   ->  -1.0   (идеальная убывающая)
    pearson([1, 2, 3, 4], [1, -1, -1, 1])  ->  0.0

    Формула: сумма произведений отклонений, делённая на произведение
    корней из сумм квадратов отклонений.

    Пирсон видит только прямую. Для y = x^3 он даст меньше единицы, хотя
    связь идеально монотонная — там нужен Спирмен. Он же чувствителен к
    выбросам: одна точка способна поднять r с 0.1 до 0.9.

    Ловушка: постоянный ряд. Его отклонения нулевые, знаменатель ноль,
    коэффициента не существует. Возвращаем 0.0, а не падаем.
    """
    mx, my = mean(x), mean(y)
    dx = [a - mx for a in x]
    dy = [b - my for b in y]
    denominator = math.sqrt(sum(a * a for a in dx)) * math.sqrt(sum(b * b for b in dy))
    if denominator == 0.0:
        return 0.0
    return sum(a * b for a, b in zip(dx, dy)) / denominator


def spearman(x, y):
    """Корреляция Спирмена: сила МОНОТОННОЙ связи. Пирсон, но по рангам.

    spearman([1, 2, 3], [1, 8, 27])  ->  1.0   (а Пирсон здесь меньше 1)
    spearman([1, 2, 3], [3, 2, 1])   ->  -1.0
    spearman([1, 1, 2], [1, 2, 3])   ->  0.8660254...

    Алгоритм: заменить значения их рангами (1, 2, 3, ...) и посчитать по
    рангам обычного Пирсона.

    Одинаковые значения делят ранг поровну: два одинаковых числа на местах
    1 и 2 получают по 1.5 каждое. Без усреднения рангов результат зависит
    от порядка одинаковых элементов во входе, то есть от случайности.

    Спирмен уместен для оценок и рейтингов, для ненормальных данных и
    там, где есть выбросы: ранги их сплющивают.
    """

    def ranks(values):
        order = sorted(range(len(values)), key=lambda i: values[i])
        out = [0.0] * len(values)
        i = 0
        while i < len(order):
            j = i
            # ищем правую границу группы одинаковых значений
            while j + 1 < len(order) and values[order[j + 1]] == values[order[i]]:
                j += 1
            average = (i + j) / 2.0 + 1  # ранги считаем с единицы
            for k in range(i, j + 1):
                out[order[k]] = average
            i = j + 1
        return out

    return pearson(ranks(x), ranks(y))


def welch_t(a, b):
    """t-статистика Уэлча для двух независимых выборок.

    welch_t([1, 2, 3, 4, 5], [2, 3, 4, 5, 6])  ->  -1.0
    welch_t([1, 2, 3], [1, 2, 3])              ->  0.0
    welch_t([1, 1, 1], [2, 2, 2])              ->  -inf

    Формула: (mean(a) - mean(b)) / sqrt(var(a)/n_a + var(b)/n_b), дисперсии
    выборочные. Вариант Уэлча не требует равных дисперсий — бери его по
    умолчанию, обычный двухвыборочный t-тест этого требует и врёт, когда
    условие нарушено.

    Знак говорит, чья средняя больше; порядок аргументов его переворачивает.

    Главное свойство: при том же самом различии средних |t| растёт с
    размером выборок. Поэтому на миллионе примеров «значимым» становится
    что угодно, и одной t-статистики для решения мало — нужен ещё
    размер эффекта.

    Если обе выборки постоянны, стандартная ошибка нулевая. При разных
    средних отношение имеет соответствующий знак и бесконечный модуль;
    при одинаковых средних получается неопределённость 0/0, то есть nan.
    """
    denominator = math.sqrt(variance(a) / len(a) + variance(b) / len(b))
    difference = mean(a) - mean(b)
    if denominator == 0.0:
        return math.copysign(math.inf, difference) if difference != 0.0 else math.nan
    return difference / denominator


def cohens_d(a, b):
    """Размер эффекта Коэна: разность средних в объединённых сигмах.

    cohens_d([1, 2, 3, 4, 5], [2, 3, 4, 5, 6])  ->  -0.63245553...
    cohens_d([1, 2, 3], [1, 2, 3])              ->  0.0
    cohens_d([1, 1, 1], [2, 2, 2])              ->  -inf

    Объединённое стандартное отклонение:
        sqrt(((n_a - 1) * var(a) + (n_b - 1) * var(b)) / (n_a + n_b - 2))

    Ориентиры: 0.2 — маленький эффект, 0.5 — средний, 0.8 — большой.

    В отличие от t-статистики размер эффекта почти НЕ зависит от объёма
    данных. В этом весь смысл: t отвечает «различие реально?», d отвечает
    «различие вообще стоит внимания?». Отчитываться нужно обоими.

    При нулевом разбросе разных постоянных групп стандартизованное различие
    бесконечно. Если постоянные группы совпадают, это 0/0 и ответ — nan,
    а не притворный нулевой эффект.
    """
    na, nb = len(a), len(b)
    pooled = math.sqrt(
        ((na - 1) * variance(a) + (nb - 1) * variance(b)) / (na + nb - 2)
    )
    difference = mean(a) - mean(b)
    if pooled == 0.0:
        return math.copysign(math.inf, difference) if difference != 0.0 else math.nan
    return difference / pooled


def bootstrap_ci(values, statistic=mean, iterations=1000, alpha=0.05, seed=0):
    """Доверительный интервал бутстрэпом: кортеж (нижняя, верхняя).

    bootstrap_ci([5.0] * 20)               ->  (5.0, 5.0)
    bootstrap_ci(list(range(101)))         ->  интервал, накрывающий 50.0
    bootstrap_ci(data, statistic=lambda s: percentile(s, 50))  ->  CI медианы

    Алгоритм: iterations раз берём выборку того же размера С ВОЗВРАЩЕНИЕМ,
    считаем на ней statistic, складываем в список. Границы интервала —
    перцентили этого списка: alpha/2 и 1 - alpha/2 (для alpha=0.05 это
    2.5 и 97.5).

    «С возвращением» — не деталь: без него каждая выборка равна исходной и
    разброса не возникает вовсе.

    Для воспроизводимости заводи собственный генератор random.Random(seed),
    а не общий random: глобальный сид может испортить кто угодно.

    Зачем это в ML: точность на тесте — одно число без погрешности.
    Бутстрэп даёт погрешность для ЛЮБОЙ метрики, включая AUC и F1, где
    формулы доверительного интервала просто нет.
    """
    rng = random.Random(seed)
    n = len(values)
    estimates = []
    for _ in range(iterations):
        # randrange быстрее, чем rng.choices: не строит промежуточных весов
        resample = [values[rng.randrange(n)] for _ in range(n)]
        estimates.append(statistic(resample))
    return (
        percentile(estimates, 100 * alpha / 2),
        percentile(estimates, 100 * (1 - alpha / 2)),
    )
