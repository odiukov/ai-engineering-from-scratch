def bad_minutes(outages, granularity_s=60.0):
    """Сколько минут окна считаются «плохими». outages — пары (начало, длительность) в секундах.

    Вернуть число ПЛОХИХ ЕДИНИЦ SLI (не секунд).

    bad_minutes([(0.0, 300.0)])                            ->  5.0
    bad_minutes([(0.0, 30.0), (600.0, 30.0)])              ->  2.0
    bad_minutes([(0.0, 300.0)], granularity_s=1.0)         ->  300.0
    bad_minutes([(0.0, 30.0), (600.0, 30.0)], granularity_s=1.0)  ->  60.0

    Вот здесь и живёт главный подвох SRE. Суммарная длительность в двух
    первых примерах разная, зато сравни это:

        один сбой на 300 секунд           -> 5 плохих минут
        десять сбоев по 30 секунд подряд  -> 10 плохих минут

    Одна и та же суммарная недоступность (300 с), а бюджет прожжён вдвое
    быстрее. Причина не в сервисе, а в ОПРЕДЕЛЕНИИ SLI: минута считается
    плохой целиком, даже если лежало полминуты. При посекундном SLI
    (granularity_s=1.0) оба сценария стоят ровно 300 единиц — они снова
    равны.

    Мораль: «мы уложились в SLO» без определения SLI — не утверждение.
    Частые короткие сбои дороже одного длинного ровно настолько, насколько
    грубая гранулярность округляет вверх.

    Перекрывающиеся сбои не считаются дважды: одна и та же минута плохая
    один раз, сколько бы алертов в неё ни попало.

    Длительность <= 0 — ValueError: сбой нулевой длины обычно значит, что
    время закрытия инцидента не проставлено.
    """
