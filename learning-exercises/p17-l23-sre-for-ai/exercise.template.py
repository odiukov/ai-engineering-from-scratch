def error_budget(slo_target, window_s, outages, granularity_s=60.0):
    """Бюджет ошибок за окно: сколько было, сколько прожжено, с какой скоростью.

    Вернуть {"allowed", "spent", "remaining", "consumed_fraction", "burn_rate"}.

    error_budget(0.999, 30*24*3600, [])
        ->  allowed 43.2 минуты за месяц, spent 0, burn_rate 0.0
    error_budget(0.999, 30*24*3600, [(0.0, 300.0)])
        ->  spent 5.0, remaining 38.2, burn_rate около 0.1157

    allowed = (1 - slo_target) * длина окна в единицах SLI. Для 99.9% за
    30 дней это 43200 минут * 0.001 = 43.2 минуты. Та самая «три девятки —
    43 минуты в месяц».

    burn_rate = spent / allowed — какая доля бюджета этого окна уже
    израсходована. 1.0 означает «бюджет выбран ровно в ноль», 2.0 — «сожгли
    вдвое больше, чем окно позволяет».

    Смысл burn_rate целиком зависит от длины окна, и в этом весь фокус
    multiwindow-правила: одна и та же минута простоя при SLO 99.9% даёт
    burn_rate 0.023 на месячном окне (1 / 43.2) и 16.7 на часовом
    (1 / 0.06). Первое число говорит «месяц ещё вытянем», второе — «прямо
    сейчас горит». Оба верны, и решение принимается по обоим сразу
    (см. release_decision).

    Отрицательный remaining — норма, а не ошибка: бюджет можно перерасходовать,
    и именно это число идёт в разговор с продуктом.

    slo_target вне (0, 1) — ValueError. SLO = 1.0 означает нулевой бюджет, и
    деление на ноль в burn_rate было бы честнее молчаливой бесконечности.
    """
    raise NotImplementedError


def release_decision(budget, burn_fast, burn_slow, fast=FAST_BURN, slow=SLOW_BURN):
    """Замораживать релизы или нет. Вернуть ("freeze"|"slow"|"ship", причина).

    budget — словарь от error_budget. burn_fast / burn_slow — скорости
    прожигания за короткое и длинное окно (обычно 1 час и 6 часов),
    посчитанные тем же error_budget по своим окнам.

    release_decision(бюджет_на_нуле, 1.0, 1.0)   ->  ("freeze", ...)
    release_decision(здоровый, 20.0, 8.0)        ->  ("freeze", ...)
    release_decision(здоровый, 20.0, 1.0)        ->  ("slow", ...)
    release_decision(здоровый, 1.0, 1.0)         ->  ("ship", ...)

    Правило из multiwindow burn-rate: тревога поднимается, только когда
    БЫСТРОЕ окно И медленное окно горят одновременно. Одно быстрое окно —
    это, скорее всего, короткий всплеск, который уже кончился; заморозить
    релизы по нему значит перестать выпускать вообще.

    Три исхода, а не два: "slow" — быстрое окно горит, медленное молчит.
    Релизы идут, но по одному и с наблюдением. Бинарное «можно / нельзя»
    приводит к тому, что заморозку начинают обходить.

    Исчерпанный бюджет бьёт всё остальное: если remaining <= 0, релизы
    заморожены независимо от текущих скоростей. Бюджет — это про месяц, а
    не про последний час.
    """
    raise NotImplementedError
