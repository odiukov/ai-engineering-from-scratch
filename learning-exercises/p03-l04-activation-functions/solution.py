"""
Функции активации — эталон.

Открывай ПОСЛЕ своих зелёных тестов.
"""

import math


def sigmoid(x):
    """Сигмоида: 1 / (1 + e^(-x)), диапазон (0, 1).

    sigmoid(0.0)  ->  0.5
    sigmoid(2.0)  ->  0.88079...

    Зажми x в [-500, 500] перед exp, иначе на x = -1000 будет OverflowError.
    """
    x = max(-500.0, min(500.0, x))
    return 1.0 / (1.0 + math.exp(-x))


def d_sigmoid(x):
    """Производная сигмоиды: s(x) * (1 - s(x)).

    d_sigmoid(0.0)  ->  0.25   (это её максимум)
    d_sigmoid(5.0)  ->  0.00664...

    Потолок 0.25 — приговор глубоким сигмоидным сетям: десять слоёв
    умножают градиент максимум на 0.25^10, то есть на одну миллионную.
    """
    s = sigmoid(x)
    return s * (1.0 - s)


def tanh_act(x):
    """Гиперболический тангенс: диапазон (-1, 1), центрирован в нуле.

    tanh_act(0.0)  ->  0.0
    tanh_act(1.0)  ->  0.76159...

    Бери math.tanh — он уже написан численно устойчиво. Ручная формула
    (e^x - e^-x)/(e^x + e^-x) переполнится на x = 800.
    """
    return math.tanh(x)


def d_tanh(x):
    """Производная тангенса: 1 - tanh(x)^2.

    d_tanh(0.0)  ->  1.0   (максимум, вчетверо больше сигмоидного)
    d_tanh(2.0)  ->  0.07065...

    Единица против 0.25 — вот почему tanh дольше держит градиент. Но
    затухание всё равно есть: на краях производная так же уходит в ноль.
    """
    t = math.tanh(x)
    return 1.0 - t * t


def relu(x):
    """ReLU: max(0, x).

    relu(3.0)   ->  3.0
    relu(-3.0)  ->  0.0
    """
    return x if x > 0.0 else 0.0


def d_relu(x):
    """Производная ReLU: 1 при x > 0, иначе 0.

    d_relu(3.0)   ->  1.0
    d_relu(-3.0)  ->  0.0
    d_relu(0.0)   ->  0.0   (в нуле производной нет, берём 0 по соглашению)

    Ровно единица на всей положительной полуоси — градиент проходит слой
    без потерь. Это и сделало глубокие сети обучаемыми. Цена — мёртвые
    нейроны: если z всегда отрицателен, производная всегда 0, и нейрон
    уже никогда не оживёт.
    """
    return 1.0 if x > 0.0 else 0.0


def leaky_relu(x, alpha=0.01):
    """Leaky ReLU: x при x > 0, иначе alpha * x.

    leaky_relu(3.0)   ->  3.0
    leaky_relu(-3.0)  ->  -0.03

    Небольшой наклон слева — самое дешёвое лекарство от мёртвых нейронов.
    """
    return x if x > 0.0 else alpha * x


def d_leaky_relu(x, alpha=0.01):
    """Производная Leaky ReLU: 1 при x > 0, иначе alpha.

    d_leaky_relu(3.0)   ->  1.0
    d_leaky_relu(-3.0)  ->  0.01
    d_leaky_relu(0.0)   ->  0.01   (то же соглашение, что у d_relu)

    Именно эта alpha вместо нуля и оставляет мёртвому нейрону шанс.
    """
    return 1.0 if x > 0.0 else alpha


def gelu(x):
    """GELU: x * Phi(x), где Phi — функция распределения стандартной нормали.

    gelu(0.0)   ->  0.0
    gelu(3.0)   ->  2.99595...
    gelu(-3.0)  ->  -0.00405...

    Phi(x) = 0.5 * (1 + erf(x / sqrt(2))), erf есть в math.
    Смысл: вход умножается на вероятность того, что он положителен.
    Отсюда мягкое пропускание вместо жёсткого обрезания у ReLU.

    Активация по умолчанию в BERT, GPT и почти всех трансформерах.
    В статьях часто пишут приближение через tanh — оно быстрее, но это
    именно приближение, и его производная не совпадает с производной
    точной формулы. Здесь берём точную.
    """
    return 0.5 * x * (1.0 + math.erf(x / math.sqrt(2.0)))


def d_gelu(x):
    """Производная GELU: Phi(x) + x * phi(x).

    d_gelu(0.0)  ->  0.5
    d_gelu(3.0)  ->  1.01194...

    Phi — та же функция распределения, phi — плотность нормали,
    e^(-x^2/2) / sqrt(2*pi). Правило произведения: (x * Phi)' = Phi + x*Phi',
    а Phi' и есть плотность.

    Обрати внимание: производная бывает больше единицы и бывает
    отрицательной. GELU немонотонна, и это не баг.
    """
    phi_cdf = 0.5 * (1.0 + math.erf(x / math.sqrt(2.0)))
    phi_pdf = math.exp(-0.5 * x * x) / math.sqrt(2.0 * math.pi)
    return phi_cdf + x * phi_pdf


def swish(x):
    """Swish (он же SiLU): x * sigmoid(x).

    swish(0.0)   ->  0.0
    swish(3.0)   ->  2.85772...
    swish(-3.0)  ->  -0.14227...

    Найдена автоматическим поиском по пространству функций активации:
    нейросеть подобрала деталь для нейросетей. Используется в EfficientNet.
    """
    return x * sigmoid(x)


def d_swish(x):
    """Производная Swish: s(x) + x * s(x) * (1 - s(x)).

    d_swish(0.0)  ->  0.5
    d_swish(3.0)  ->  1.08810...

    Правило произведения: (x * s)' = s + x * s'. Сигмоиду считаем один раз
    и переиспользуем — второй вызов exp здесь лишний.
    """
    s = sigmoid(x)
    return s + x * s * (1.0 - s)


def softmax(logits):
    """Softmax: вектор логитов -> распределение вероятностей.

    softmax([0.0, 0.0])       ->  [0.5, 0.5]
    softmax([1000.0, 1000.0]) ->  [0.5, 0.5]
    softmax([2.0, 1.0, 0.0])  ->  [0.66524, 0.24473, 0.09003]

    Ловушка ровно одна и она серьёзная: math.exp(1000) это OverflowError.
    Вычти максимум из всех логитов перед exp — результат не изменится
    (общий множитель сокращается в числителе и знаменателе), а переполнения
    не будет. Второй пример именно про это.

    Softmax стоит на выходе любого классификатора и внутри attention.
    """
    shift = max(logits)
    exps = [math.exp(v - shift) for v in logits]
    total = sum(exps)
    return [e / total for e in exps]


def dead_zone_fraction(derivative_fn, start=-5.0, end=5.0, n=100):
    """Доля точек отрезка, где производная по модулю меньше 0.01.

    dead_zone_fraction(d_relu)  ->  ~0.5   (вся отрицательная половина)
    dead_zone_fraction(d_tanh)  ->  0.41
    dead_zone_fraction(d_swish) ->  0.01

    Берём n точек: start + i*(end - start)/n, i от 0 до n-1.

    Где производная почти ноль, там градиент не проходит и слой не учится.
    У ReLU это ровно половина числовой оси — отсюда и мёртвые нейроны.
    """
    step = (end - start) / n
    near_zero = sum(1 for i in range(n) if abs(derivative_fn(start + i * step)) < 0.01)
    return near_zero / n


def max_derivative(derivative_fn, start=-5.0, end=5.0, n=100):
    """Наибольшая по модулю производная на отрезке — «пропускная способность».

    max_derivative(d_sigmoid)  ->  0.25
    max_derivative(d_tanh)     ->  1.0
    max_derivative(d_relu)     ->  1.0

    Точки берутся так же, как в dead_zone_fraction.

    Вот честная мера затухания градиента: слой умножает градиент максимум
    на это число. У сигмоиды 0.25, значит десять слоёв дают 0.25^10 —
    одну миллионную. У ReLU единица, и градиент доходит до первого слоя
    целым. Мёртвая зона и потолок производной — две разные болезни, мерить
    надо обе.
    """
    step = (end - start) / n
    return max(abs(derivative_fn(start + i * step)) for i in range(n))
