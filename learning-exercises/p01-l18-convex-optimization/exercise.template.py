def kkt_violations(grad_f, constraints, x, lambdas):
    """Насколько точка (x, lambdas) нарушает четыре условия KKT.

    Задача: minimize f(x) при g_i(x) <= 0. constraints — список пар
    (g_i, grad_g_i), lambdas — множители, по одному на ограничение.
    Возвращает словарь из четырёх неотрицательных невязок; все нули —
    условия выполнены.

      "stationarity"  max|grad_f + sum(lambda_i * grad_g_i)|
      "primal"        max(0, max g_i(x))        — нарушение допустимости
      "dual"          max(0, max(-lambda_i))    — отрицательный множитель
      "slackness"     max|lambda_i * g_i(x)|    — дополняющая нежёсткость

    g = lambda p: 1 - p[0] - p[1]; gg = lambda p: [-1.0, -1.0]
    kkt_violations(lambda p: [2*p[0], 2*p[1]], [(g, gg)], [0.5, 0.5], [1.0])
        ->  все четыре равны 0.0
    kkt_violations(lambda p: [2*p[0], 2*p[1]], [(g, gg)], [0.0, 0.0], [0.0])
        ->  "primal" = 1.0, остальные 0.0

    Ловушка: дополняющая нежёсткость — это |lambda_i * g_i|, модуль.
    Произведение без модуля отрицательно у неактивного ограничения и
    максимум по нему покажет ноль там, где нарушение есть.
    Ловушка: grad_f(x) может вернуть список, который вызывающий переиспользует;
    складывай в СВОЮ копию.

    Отсюда растут SVM: опорные векторы — ровно те точки, где ограничение
    активно и lambda > 0; у всех остальных lambda = 0, и на границу решения
    они не влияют.
    """
