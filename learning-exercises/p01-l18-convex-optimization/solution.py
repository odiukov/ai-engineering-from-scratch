"""
Выпуклая оптимизация — эталон.

Открывай ПОСЛЕ своих зелёных тестов.
"""

import random


def convex_combination(x, y, t):
    """Точка на отрезке между x и y: t*x + (1-t)*y. Оба — списки чисел.

    convex_combination([0.0, 0.0], [10.0, 20.0], 0.5)  ->  [5.0, 10.0]
    convex_combination([1.0], [3.0], 1.0)              ->  [1.0]
    convex_combination([1.0], [3.0], 0.25)             ->  [2.5]

    Ловушка: t — вес ПЕРВОГО аргумента. При t=1 получается x, при t=0 — y.
    Ловушка: верни НОВЫЙ список, x и y менять нельзя.

    Отсюда растёт всё определение выпуклости: и множества, и функции
    проверяются именно на таких точках отрезка.
    """
    # zip вместо range(len(...)): короче и не даёт промахнуться по индексу,
    # длина результата — по более короткому из списков. O(n).
    return [t * xi + (1 - t) * yi for xi, yi in zip(x, y)]


def segment_violation(f, x, y, t):
    """Насколько f нарушает определение выпуклости на отрезке [x, y] в точке t.

    Возвращает f(t*x + (1-t)*y) - (t*f(x) + (1-t)*f(y)): значение функции
    минус хорда. Для выпуклой функции результат <= 0 при любом t.

    segment_violation(lambda p: p[0] ** 2, [0.0], [2.0], 0.5)  ->  -1.0
    segment_violation(lambda p: 3 * p[0] + 1, [0.0], [2.0], 0.5)  ->  0.0
    segment_violation(lambda p: p[0] ** 3, [-2.0], [0.0], 0.5)  ->  3.0

    Ловушка: порядок вычитания. «Функция минус хорда» — положительный
    результат означает, что график вылез НАД хордой, то есть выпуклость
    сломана. Перепутаешь знак — тесты на невыпуклость позеленеют зря.
    Ловушка: один и тот же t должен весить x и слева, и справа.
    """
    mid = convex_combination(x, y, t)
    # линейная функция даст ровно 0.0, поэтому сравнивать снаружи надо
    # с допуском, а не с нулём — этим занимается check_convexity
    return f(mid) - (t * f(x) + (1 - t) * f(y))


def check_convexity(f, dim, bounds=(-5.0, 5.0), samples=200, seed=0, tol=1e-9):
    """Эмпирическая проверка выпуклости: (всё_ли_ок, число_нарушений).

    Берёт samples случайных пар точек в кубе bounds^dim и случайный t,
    считает segment_violation. Нарушение засчитывается, если оно > tol.

    check_convexity(lambda p: p[0] ** 2, 1)         ->  (True, 0)
    check_convexity(lambda p: math.sin(p[0]), 1)    ->  (False, сколько-то > 0)
    check_convexity(lambda p: p[0] * p[1], 2)       ->  (False, сколько-то > 0)

    Ловушка: заведи СВОЙ генератор random.Random(seed). Если дёргать
    глобальный random, результат начнёт зависеть от того, что в программе
    крутилось до вызова, и тест перестанет быть воспроизводимым.
    Ловушка: сравнивай с tol, а не с нулём: у линейной функции нарушение
    равно нулю лишь с точностью до float.

    Так на глаз отличают выпуклую задачу (логрегрессия, SVM, LASSO) от
    невыпуклой (нейросеть): у первой одна долина, у второй — много.
    """
    rng = random.Random(seed)  # локальный поток случайности, воспроизводимо
    lo, hi = bounds
    violations = 0
    for _ in range(samples):
        x = [rng.uniform(lo, hi) for _ in range(dim)]
        y = [rng.uniform(lo, hi) for _ in range(dim)]
        t = rng.random()
        if segment_violation(f, x, y, t) > tol:
            violations += 1
    # проверка односторонняя: ноль нарушений НЕ доказывает выпуклость,
    # он лишь не смог её опровергнуть на этой выборке
    return violations == 0, violations


def hessian_2x2(f, point, h=1e-4):
    """Численный гессиан функции двух переменных: матрица 2x2 вторых производных.

    hessian_2x2(lambda p: p[0]**2 + 3*p[0]*p[1] + p[1]**2, [0.0, 0.0])
        ->  [[2.0, 3.0], [3.0, 2.0]]
    hessian_2x2(lambda p: 5*p[0]**2 + p[1]**2, [1.0, 1.0])
        ->  [[10.0, 0.0], [0.0, 2.0]]

    Диагональ: (f(x+h) - 2*f(x) + f(x-h)) / h^2 по каждой координате.
    Смешанная: (f(++) - f(+-) - f(-+) + f(--)) / (4*h^2).

    Ловушка: h тут делится в КВАДРАТЕ. Привычные 1e-8 из первой производной
    дадут в знаменателе 1e-16 и мусор вместо ответа — h порядка 1e-4 это
    компромисс между ошибкой метода и потерей точности float.
    Ловушка: point менять нельзя, для каждого сдвига делай копию.

    Гессиан — это кривизна. Из него берут и критерий выпуклости, и шаг
    метода Ньютона, и число обусловленности.
    """
    x, y = point[0], point[1]  # распаковка вместо копий списка: дешевле
    f00 = f([x, y])
    fxx = (f([x + h, y]) - 2 * f00 + f([x - h, y])) / (h * h)
    fyy = (f([x, y + h]) - 2 * f00 + f([x, y - h])) / (h * h)
    fxy = (
        f([x + h, y + h])
        - f([x + h, y - h])
        - f([x - h, y + h])
        + f([x - h, y - h])
    ) / (4 * h * h)
    # для гладкой функции d2f/dxdy == d2f/dydx (теорема Шварца), поэтому
    # считаем смешанную производную один раз: 4 вызова f вместо 8
    return [[fxx, fxy], [fxy, fyy]]


def eigenvalues_2x2(H):
    """Собственные числа симметричной матрицы 2x2, по возрастанию.

    eigenvalues_2x2([[2.0, 0.0], [0.0, 3.0]])    ->  [2.0, 3.0]
    eigenvalues_2x2([[2.0, 3.0], [3.0, 2.0]])    ->  [-1.0, 5.0]
    eigenvalues_2x2([[10.0, 0.0], [0.0, 2.0]])   ->  [2.0, 10.0]

    Формула: half = (a+d)/2, disc = ((a-d)/2)^2 + b*c, ответ half -+ sqrt(disc).

    Ловушка: если disc < 0, вещественных собственных чисел нет (матрица
    несимметричная) — брось ValueError, а не считай sqrt от минуса.
    Ловушка: возвращай отсортированно, иначе «наименьшее собственное
    число» придётся искать вызывающему.

    Оба числа >= 0 — гессиан положительно полуопределён, функция в этой
    точке выпукла. Разные знаки — седло. Отношение большего к меньшему —
    число обусловленности: чем оно больше, тем уже овраг и тем медленнее
    ползёт градиентный спуск.
    """
    a, b, c, d = H[0][0], H[0][1], H[1][0], H[1][1]
    half_trace = (a + d) / 2
    # ((a-d)/2)^2 + b*c устойчивее, чем tr^2/4 - det: там два больших
    # почти равных числа вычитаются и теряются значащие разряды
    disc = ((a - d) / 2) ** 2 + b * c
    if disc < 0:
        raise ValueError("матрица не симметрична: собственные числа комплексные")
    root = disc ** 0.5
    return [half_trace - root, half_trace + root]


def newton_step(point, grad, H):
    """Один шаг метода Ньютона в 2D: point - H^(-1) * grad.

    newton_step([1.0, 1.0], [10.0, 2.0], [[10.0, 0.0], [0.0, 2.0]])
        ->  [0.0, 0.0]
    newton_step([3.0, 0.0], [6.0, 0.0], [[2.0, 0.0], [0.0, 2.0]])
        ->  [0.0, 0.0]

    Никакого learning rate: размер шага целиком задаёт кривизна. На
    квадратичной функции такой шаг попадает в минимум ровно за один раз.

    Ловушка: нужен H^(-1) * grad, а не H * grad. Умножение на саму матрицу
    даст шаг в ту же сторону, но неправильной длины, и тест это поймает.
    Ловушка: если определитель H близок к нулю, обратной матрицы нет —
    брось ValueError, а не дели на ноль.
    """
    a, b, c, d = H[0][0], H[0][1], H[1][0], H[1][1]
    det = a * d - b * c
    if abs(det) < 1e-15:
        raise ValueError("вырожденный гессиан: обратной матрицы нет")
    # решаем H*dx = grad по Крамеру, не строя H^(-1) целиком:
    # меньше делений, меньше накопленной ошибки
    dx0 = (d * grad[0] - b * grad[1]) / det
    dx1 = (a * grad[1] - c * grad[0]) / det
    return [point[0] - dx0, point[1] - dx1]


def newton_minimize(grad_f, hess_f, x0, steps=50, tol=1e-12):
    """Метод Ньютона до сходимости. Вернуть найденную точку (список из 2 чисел).

    Каждый шаг: посчитать градиент, посчитать гессиан, шагнуть. Остановиться
    досрочно, когда квадрат нормы градиента стал меньше tol.

    newton_minimize(lambda p: [10*p[0], 2*p[1]],
                    lambda p: [[10.0, 0.0], [0.0, 2.0]],
                    [10.0, 10.0], steps=1)      ->  [0.0, 0.0]
    newton_minimize(lambda p: [2*(p[0]-3), 2*(p[1]+1)],
                    lambda p: [[2.0, 0.0], [0.0, 2.0]],
                    [0.0, 0.0])                 ->  [3.0, -1.0]

    Ловушка: критерий остановки проверяй ДО шага. Если стартовая точка уже
    оптимальна, функция обязана вернуть её без единого шага.
    Ловушка: x0 менять нельзя — работай с копией.

    Ради этого всё и затевалось: там, где градиентному спуску нужны сотни
    шагов на вытянутом овраге, Ньютону хватает единиц. Цена — O(n^2) памяти
    на гессиан и O(n^3) на его обращение, поэтому в глубоком обучении с его
    миллионами весов метод не применяют.
    """
    point = list(x0)  # копия: список вызывающего остаётся нетронутым
    for _ in range(steps):
        g = grad_f(point)
        # сравниваем квадрат нормы: sqrt тут не нужен и стоит времени
        if sum(gi * gi for gi in g) < tol:
            break
        point = newton_step(point, g, hess_f(point))
    return point


def kkt_violations(grad_f, constraints, x, lambdas):
    """Насколько точка (x, lambdas) нарушает четыре условия KKT.

    Задача: minimize f(x) при g_i(x) <= 0. constraints — список пар
    (g_i, grad_g_i), lambdas — множители, по одному на ограничение.
    Возвращает словарь из четырёх неотрицательных невязок; все нули —
    условия выполнены.

      "stationarity"  max|grad_f + sum(lambda_i * grad_g_i)|
      "primal"        max(0, max g_i(x))        — нарушение допустимости
      "dual"          max(0, max(-lambda_i))    — отрицательный множитель
      "slackness"     max|lambda_i * g_i(x)|    — дополняющая нежёсткость

    g = lambda p: 1 - p[0] - p[1]; gg = lambda p: [-1.0, -1.0]
    kkt_violations(lambda p: [2*p[0], 2*p[1]], [(g, gg)], [0.5, 0.5], [1.0])
        ->  все четыре равны 0.0
    kkt_violations(lambda p: [2*p[0], 2*p[1]], [(g, gg)], [0.0, 0.0], [0.0])
        ->  "primal" = 1.0, остальные 0.0

    Ловушка: дополняющая нежёсткость — это |lambda_i * g_i|, модуль.
    Произведение без модуля отрицательно у неактивного ограничения и
    максимум по нему покажет ноль там, где нарушение есть.
    Ловушка: grad_f(x) может вернуть список, который вызывающий переиспользует;
    складывай в СВОЮ копию.

    Отсюда растут SVM: опорные векторы — ровно те точки, где ограничение
    активно и lambda > 0; у всех остальных lambda = 0, и на границу решения
    они не влияют.
    """
    g_vals = [g(x) for g, _ in constraints]
    total = list(grad_f(x))  # копия: чужой список не портим
    for lam, (_, grad_g) in zip(lambdas, constraints):
        gg = grad_g(x)
        for i in range(len(total)):
            total[i] += lam * gg[i]
    # default= вместо проверки на пустоту: задача без ограничений тоже
    # законна, там KKT вырождается в «градиент равен нулю»
    return {
        "stationarity": max((abs(v) for v in total), default=0.0),
        "primal": max((max(0.0, v) for v in g_vals), default=0.0),
        "dual": max((max(0.0, -lam) for lam in lambdas), default=0.0),
        "slackness": max(
            (abs(lam * v) for lam, v in zip(lambdas, g_vals)), default=0.0
        ),
    }
