"""
Основы аудио: волна, дискретизация, преобразование Фурье — эталон.

Открывай ПОСЛЕ своих зелёных тестов.
"""

import math


def sine(freq_hz, sr, seconds, amp=0.5):
    """Синтезировать синусоиду: список из int(sr * seconds) отсчётов.

    Отсчёт номер i соответствует моменту времени t = i / sr секунд,
    значение равно amp * sin(2*pi*freq_hz*t).

    len(sine(440, 16000, 1.0))  ->  16000
    sine(440, 16000, 1.0)[0]    ->  0.0      (синус нуля)
    sine(1, 4, 1.0)             ->  [0.0, 0.5, ~0.0, -0.5]

    Ловушка: делить надо на sr, а не на длину клипа. Частота — это
    «сколько периодов в секунду», а секунда — это ровно sr отсчётов.

    Зачем в AI: любой синтетический тест-сигнал для аудио-пайплайна
    начинается отсюда — чистый тон с известной частотой легко проверить.
    """
    n = int(sr * seconds)
    # i / sr — время в секундах; перемножать в таком порядке дешевле,
    # чем каждый раз считать отдельную переменную времени
    return [amp * math.sin(2 * math.pi * freq_hz * i / sr) for i in range(n)]


def nyquist(sr):
    """Частота Найквиста: максимальная частота, которую sr ещё различает.

    nyquist(16000)  ->  8000.0
    nyquist(8000)   ->  4000.0   (телефония режет согласные, отсюда и WER)

    Теорема Найквиста-Шеннона: частота дискретизации sr однозначно
    представляет частоты до sr/2. Всё, что выше, — искажается.
    """
    return sr / 2


def alias_frequency(freq_hz, sr):
    """Какая частота реально появится в спектре, если тон freq_hz снят на sr.

    alias_frequency(3000, 16000)  ->  3000.0   (ниже Найквиста — как есть)
    alias_frequency(7000, 10000)  ->  3000.0   (7 кГц при sr=10 кГц «свернулся»)
    alias_frequency(10000, 10000) ->  0.0      (ровно sr — выглядит как DC)

    Механика: сначала частота уходит по кругу с периодом sr (остаток от
    деления), а потом, если попала в верхнюю половину, отражается от
    Найквиста вниз: sr - остаток.

    Зачем в AI: наивный ресемплинг «брать каждый третий отсчёт» без
    низкочастотного фильтра сворачивает высокие частоты в речевой диапазон
    и модель учится на призраках.
    """
    # abs: отрицательная частота физически неотличима от положительной
    f = abs(freq_hz) % sr
    return f if f <= sr / 2 else sr - f


def bin_to_hz(k, sr, n_fft):
    """Частота в герцах, которой соответствует бин номер k.

    bin_to_hz(0, 16000, 1024)    ->  0.0        (DC, постоянная составляющая)
    bin_to_hz(1, 16000, 1024)    ->  15.625     (разрешение = sr / n_fft)
    bin_to_hz(512, 16000, 1024)  ->  8000.0     (бин Найквиста)

    Разрешение по частоте — это sr / n_fft. Хочешь различать 10 Гц при
    16 кГц — бери окно минимум в 1600 отсчётов.
    """
    return k * sr / n_fft


def dft_magnitudes(x):
    """Модули коэффициентов DFT: список из len(x) неотрицательных чисел.

    Для каждого бина k считается сумма x[n] * e^(-2i*pi*k*n/N), возвращается
    её модуль. Фаза отбрасывается — для «на какой частоте энергия» она не
    нужна.

    dft_magnitudes([1, 1, 1, 1])   ->  [4.0, 0.0, 0.0, 0.0]  (чистый DC)
    dft_magnitudes([1, -1, 1, -1]) ->  [0.0, 0.0, 4.0, 0.0]  (частота Найквиста)

    Ловушка: у вещественного сигнала спектр симметричен, бин k и бин N-k
    имеют одинаковый модуль. Полезной информации — только в первой
    половине, поэтому librosa и torch возвращают n_fft//2 + 1 бинов.

    Сложность O(N^2). Это нормально для N=256 в учебном коде и совершенно
    неприемлемо для реального аудио — там используют FFT за O(N log N).
    """
    N = len(x)
    out = []
    for k in range(N):
        re = 0.0
        im = 0.0
        for n, v in enumerate(x):
            # знак минус в показателе — соглашение прямого преобразования
            angle = -2 * math.pi * k * n / N
            re += v * math.cos(angle)
            im += v * math.sin(angle)
        # hypot вместо sqrt(re*re + im*im): не переполняется на больших числах
        out.append(math.hypot(re, im))
    return out


def dominant_frequency(x, sr):
    """Частота самого сильного бина спектра, в герцах.

    Тон 440 Гц, снятый на 16 кГц окном из 1600 отсчётов, даст 440.0.

    dominant_frequency(sine(3000, 16000, 0.01), 16000)  ->  3000.0

    Ловушка: искать максимум надо только в первой половине спектра,
    до бина len(x)//2 включительно. В зеркальной половине сидит такой же
    по величине пик, и argmax по всему спектру запросто вернёт sr - f.
    """
    mags = dft_magnitudes(x)
    half = len(x) // 2
    # только «полезная» половина: выше Найквиста бины — зеркало нижних
    k = max(range(half + 1), key=lambda i: mags[i])
    return bin_to_hz(k, sr, len(x))


def float_to_pcm16(x):
    """Float-отсчёты из [-1, 1] в 16-битный PCM: целые из [-32767, 32767].

    float_to_pcm16([0.0, 1.0, -1.0])  ->  [0, 32767, -32767]
    float_to_pcm16([1.5])             ->  [32767]

    Ловушка: значения за пределами [-1, 1] надо КЛИППИРОВАТЬ, а не
    умножать как есть. 1.5 * 32767 не влезет в int16 и при записи в WAV
    завернётся в отрицательное число — вместо громкого звука получится
    треск.
    """
    out = []
    for v in x:
        # сначала обрезаем, потом масштабируем: обратный порядок
        # пришлось бы сравнивать с 32767 и читалось бы хуже
        clipped = max(-1.0, min(1.0, v))
        out.append(int(round(clipped * 32767)))
    return out


def pcm16_to_float(samples):
    """16-битный PCM обратно во float-отсчёты в [-1, 1].

    pcm16_to_float([0, 32767, -32767])  ->  [0.0, 1.0, -1.0]

    Это то, что делают soundfile.read(dtype="float32") и torchaudio.load:
    файл на диске хранит int16, а модель получает float.
    """
    return [s / 32767.0 for s in samples]
