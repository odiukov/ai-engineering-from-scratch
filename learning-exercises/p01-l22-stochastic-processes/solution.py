"""
Случайные процессы — эталон.

Открывай ПОСЛЕ своих зелёных тестов.

Соглашения по данным, они одинаковы во всех функциях:
  * матрица переходов P — список списков, P[i][j] это вероятность перейти
    из состояния i в состояние j; каждая СТРОКА суммируется в 1;
  * состояния — целые индексы 0..n-1, они же номера строк и столбцов P;
  * распределение по состояниям — плоский список длины n с суммой 1;
  * траектория — список длины n_steps + 1: нулевой элемент это начало,
    дальше по одному элементу на каждый шаг;
  * источник случайности всегда приходит параметром rng (объект
    random.Random). Глобальный random внутри функций не используется:
    иначе один и тот же вызов даёт разный ответ, и ни воспроизвести
    эксперимент, ни отладить его нельзя.
"""

import math


def step_distribution(dist, P):
    """Один шаг цепи Маркова: куда переедет распределение по состояниям.

    step_distribution([1.0, 0.0], [[0.9, 0.1], [0.5, 0.5]])  ->  [0.9, 0.1]
    step_distribution([0.5, 0.5], [[0.9, 0.1], [0.5, 0.5]])  ->  [0.7, 0.3]

    dist[i] — вероятность быть сейчас в состоянии i, P[i][j] — вероятность
    перейти из i в j.

    Ловушка первая: строки и столбцы очень легко перепутать. Проверка на
    месте — ответ обязан остаться распределением: если сумма уехала от 1,
    значит суммирование идёт не по тому индексу.
    Ловушка вторая: dist менять нельзя, вызывающий отдал свой список.

    Ровно этот шаг делает диффузионная модель на прямом проходе и языковая
    модель, когда по текущему состоянию считает распределение следующего
    токена.
    """
    n = len(P)
    # суммируем по i (откуда пришли), а не по j: в новое состояние j даёт
    # вклад каждое старое состояние i со своим весом dist[i].
    # Новый список, старый не трогаем — вход остаётся нетронутым.
    return [sum(dist[i] * P[i][j] for i in range(n)) for j in range(n)]


def distribution_after_n_steps(dist, P, n):
    """Распределение после n шагов цепи: n раз подряд один шаг.

    distribution_after_n_steps([1.0, 0.0], [[0.9, 0.1], [0.5, 0.5]], 0)
        ->  [1.0, 0.0]
    distribution_after_n_steps([1.0, 0.0], [[0.9, 0.1], [0.5, 0.5]], 2)
        ->  [0.86, 0.14]

    При n = 0 ничего не происходит, но вернуть надо КОПИЮ, а не сам dist:
    иначе вызывающий получит свой же список и случайно испортит его позже.

    Ловушка: каждое умножение добавляет крошечную ошибку округления, и на
    сотнях шагов сумма может отойти от 1 в последних знаках. Это нормально,
    но помнить об этом стоит — именно поэтому в стационарном распределении
    ниже результат нормируют.
    """
    out = list(dist)  # копия сразу: при n = 0 вернём её же, а не вход
    for _ in range(n):
        # переиспользуем один шаг, а не переписываем формулу заново:
        # исправлять порядок индексов тогда придётся только в одном месте
        out = step_distribution(out, P)
    return out


def stationary_distribution(P, tol=1e-12, max_steps=10000):
    """Стационарное распределение pi цепи: неподвижная точка pi = pi * P.

    stationary_distribution([[0.9, 0.1], [0.5, 0.5]])  ->  [0.8333.., 0.1667..]
    stationary_distribution([[1.0, 0.0], [0.5, 0.5]])  ->  [1.0, 0.0]

    Стартуем из равномерного распределения и итерируем «ленивую» цепь:
    на каждом шаге усредняем текущее распределение и обычный шаг по P.
    Это равносильно матрице (I + P) / 2: её стационарные распределения те
    же, но периодические колебания гасятся. Если max_steps всё же исчерпан
    до достижения tol, функция бросает RuntimeError вместо тихого возврата
    нестационарного приближения.

    Ловушка: ошибка округления накапливается, поэтому сумма ответа
    обязана быть ровно распределением — за этим надо проследить отдельно.

    Стационарное распределение — это то, к чему сходится MCMC, и то, что
    считает PageRank.
    """
    n = len(P)
    # равномерный старт: он всегда допустим и не требует знать ответ заранее
    dist = [1.0 / n] * n
    for _ in range(max_steps):
        stepped = step_distribution(dist, P)
        # Половинный self-loop убирает периодичность, не меняя pi = pi P.
        nxt = [(current + moved) / 2.0 for current, moved in zip(dist, stepped)]
        # критерий по максимальному отклонению координаты, а не по сумме:
        # сумма может совпасть у двух совсем разных распределений
        done = max(abs(a - b) for a, b in zip(nxt, dist)) < tol
        dist = nxt
        if done:
            break
    else:
        raise RuntimeError(f"стационарное распределение не сошлось за {max_steps} шагов")
    # финальная нормировка: за сотни умножений сумма уезжает от 1 в
    # последних знаках, а на выходе обязано быть распределение
    total = sum(dist)
    return [x / total for x in dist]


def empirical_distribution(states, n_states):
    """Эмпирическая частота состояний: какую долю времени цепь провела в каждом.

    empirical_distribution([0, 1, 1, 1], 2)  ->  [0.25, 0.75]
    empirical_distribution([0, 0, 0], 2)     ->  [1.0, 0.0]

    n_states передаётся отдельно, потому что по самой траектории не видно,
    сколько у цепи состояний. Состояние, в котором цепь ни разу не побывала,
    обязано получить 0.0, а длина ответа — совпасть с n_states.

    Пустая траектория — ValueError: делить на ноль нечестно.

    Этим сравнивают симуляцию с теорией: длинный прогон цепи должен дать
    примерно то же, что и стационарное распределение.
    """
    if not states:
        raise ValueError("пустая траектория: делить не на что")
    # один проход по траектории: O(len(states)), а не O(len * n_states),
    # как получилось бы при подсчёте states.count(s) для каждого состояния
    counts = [0] * n_states
    for s in states:
        counts[s] += 1
    total = len(states)
    return [c / total for c in counts]


def simulate_markov_chain(P, start, n_steps, rng):
    """Траектория цепи Маркова: список из n_steps + 1 состояний, первое — start.

    rng = random.Random(0)
    simulate_markov_chain([[1.0, 0.0], [0.5, 0.5]], 0, 3, rng)  ->  [0, 0, 0, 0]
    simulate_markov_chain([[0.0, 1.0], [1.0, 0.0]], 0, 4, rng)  ->  [0, 1, 0, 1, 0]

    Следующее состояние выбирается по СТРОКЕ P[текущее]: тянем одно
    rng.random() и идём по накопленной сумме вероятностей строки, пока не
    перевалим за него.

    Ловушка: длина ответа n_steps + 1, а не n_steps — начальное состояние
    тоже часть траектории. И rng приходит параметром, не создавай его внутри:
    тест обязан уметь повторить прогон.

    Это же категориальное сэмплирование стоит внутри генерации токенов и
    внутри шага среды в RL.
    """
    states = [start]
    current = start
    for _ in range(n_steps):
        u = rng.random()
        row = P[current]
        acc = 0.0
        # обратное преобразование: один вызов rng на шаг. Строить кумулятивные
        # суммы заранее смысла нет — строка короткая, а память лишняя
        for j, p in enumerate(row):
            acc += p
            if u < acc:
                current = j
                break
        else:
            # сюда попадаем, только если сумма строки чуть меньше 1 из-за
            # округления: отдаём последнее состояние, а не падаем
            current = len(row) - 1
        states.append(current)
    return states


def random_walk_1d(n_steps, rng):
    """Одномерное случайное блуждание: позиции, старт 0, каждый шаг +1 или -1.

    len(random_walk_1d(100, rng))  ->  101
    random_walk_1d(3, rng)         ->  [0, 1, 0, -1]   (одна из возможных)
    random_walk_1d(0, rng)         ->  [0]

    Возвращать надо ВСЕ позиции, а не только последнюю: по траектории потом
    считают и разброс, и время до первого возврата в ноль.

    Ловушка: блуждание честное, среднее смещение равно нулю, но разброс
    растёт — дисперсия позиции после n шагов равна n, то есть типичное
    расстояние от нуля это sqrt(n), а не константа.

    Тот же корень из n вылезает в шуме SGD и в длине случайных обходов графа
    (Node2Vec).
    """
    positions = [0]
    x = 0
    for _ in range(n_steps):
        # накапливаем позицию на лету: хранить отдельно шаги и потом брать
        # кумулятивную сумму — лишний проход по списку
        x += rng.choice((-1, 1))
        positions.append(x)
    return positions


def brownian_motion(n_steps, dt, rng):
    """Броуновское движение: B(0) = 0, B(t + dt) = B(t) + sqrt(dt) * z.

    z — стандартный нормальный шум (rng.gauss(0.0, 1.0)).

    len(brownian_motion(1000, 0.001, rng))  ->  1001
    brownian_motion(5, 0.25, rng)[0]        ->  0.0

    Ловушка — множитель именно sqrt(dt), а не dt. Дисперсия обязана расти
    линейно по времени: B(t) ~ N(0, t). Если поставить dt, то при мельчении
    шага траектория станет неправдоподобно гладкой, и полная дисперсия за
    то же время окажется другой.

    Это предельный случай случайного блуждания и ровно тот шум, который
    диффузионная модель подмешивает к картинке на прямом проходе.
    """
    # sqrt считаем один раз до цикла: он не меняется от шага к шагу
    scale = math.sqrt(dt)
    path = [0.0]
    x = 0.0
    for _ in range(n_steps):
        x += scale * rng.gauss(0.0, 1.0)
        path.append(x)
    return path


def langevin_dynamics(grad_U, x0, dt, temperature, n_steps, rng):
    """Динамика Ланжевена в 1D: градиентный спуск плюс шум. n_steps + 1 точек.

    Шаг: x <- x - dt * grad_U(x) + sqrt(2 * temperature) * dB,
    где dB — приращение броуновского движения с шагом dt.

    grad = lambda x: x - 3.0          # U(x) = (x - 3)^2 / 2, минимум в 3
    langevin_dynamics(grad, 0.0, 0.1, 0.0, 200, rng)[-1]  ->  ровно 3.0
    langevin_dynamics(grad, 0.0, 0.1, 1.0, 5000, rng)     ->  болтается вокруг 3

    При temperature = 0 остаётся чистый градиентный спуск, шум исчезает.
    При temperature > 0 равновесное распределение пропорционально
    exp(-U(x) / temperature): чем горячее, тем шире разброс.

    Ловушка: шум масштабируется как sqrt(2 * T * dt), то есть как sqrt(dt),
    а снос — как dt. Собрать оба слагаемых с одинаковой степенью dt — самая
    частая ошибка, и она тихо портит дисперсию.

    Отсюда растут score-based модели и SGLD: та же формула, только grad_U
    считает нейросеть.
    """
    # переиспользуем броуновскую траекторию: её приращения это ровно
    # sqrt(dt) * z, и один источник шума на две функции гарантирует, что
    # масштабирование по dt везде одинаковое
    path = brownian_motion(n_steps, dt, rng)
    noise_scale = math.sqrt(2.0 * temperature)
    x = float(x0)
    traj = [x]
    for i in range(n_steps):
        db = path[i + 1] - path[i]
        x = x - dt * grad_U(x) + noise_scale * db
        traj.append(x)
    return traj
