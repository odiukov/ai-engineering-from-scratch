"""
Hogwild! Inference: параллельные воркеры на общем кеше — эталон.

Открывай ПОСЛЕ своих зелёных тестов.

Урок про третий вид параллелизма при инференсе: не внутри последовательности
(спекулятивное декодирование) и не через протокол агентов, а N копий одной
модели, пишущих в ОДИН общий KV-кеш. Координация не программируется — она
возникает сама, потому что каждый воркер видит, что уже написали остальные.

Модель, в которой мы работаем:

  * ОБЩИЙ КЕШ — просто список записей (round, worker, category, index).
    Настоящий кеш хранит K и V; здесь важно только то, что запись видна
    всем сразу;
  * ЗАДАЧА разбита на num_categories независимых подцелей. «Категория» —
    это подцель, «index» — какой по счёту токен этой подцели воркер пишет;
  * ВОРКЕР детерминирован: прочитал видимые счётчики, выбрал категорию,
    написал токен. Никакого random — иначе тесты бы мигали, а разбираться
    в эмерджентной координации по мигающим тестам невозможно;
  * LAG моделирует асинхронность: последние lag записей воркер ещё не
    видит. lag = 0 — идеальная мгновенная видимость.

Что здесь есть настоящего: свойство «одинаковые модели без координации
делают одну и ту же работу дважды». Что здесь ненастоящее: причина, по
которой воркер меняет категорию. У QwQ и DeepSeek-R1 это рассуждение вслух,
здесь — арифметика по счётчикам. Свойство от подмены не меняется.
"""

PREFERENCE_GAP = 0.1  # насколько категория i приятнее категории i+1 сама по себе


def amdahl_time(t_serial, p, n):
    """Время задачи на n воркерах по закону Амдала, без накладных расходов.

    amdahl_time(10000, 0.7, 4)   ->  4750.0
    amdahl_time(10000, 0.7, 1)   ->  10000.0
    amdahl_time(10000, 1.0, 4)   ->  2500.0

    t_serial * ((1 - p) + p / n), где p — доля работы, которую вообще можно
    разложить на воркеры. Последовательная часть (1 - p) не ускоряется
    никогда: сколько воркеров ни добавь, ниже t_serial * (1 - p) не упасть.
    """
    return t_serial * ((1 - p) + p / n)


def hogwild_time(t_serial, p, n, c):
    """Время задачи на n воркерах Hogwild! с учётом координации.

    hogwild_time(10000, 0.7, 4, 200)  ->  5550.0
    hogwild_time(1000, 0.3, 4, 200)   ->  1575.0

    К закону Амдала добавляется c * n: каждому воркеру надо прочитать
    разросшийся общий кеш и решить, чем заняться. Расход линеен по числу
    воркеров, а выигрыш — обратно пропорционален, поэтому оптимум всегда
    внутри, а не на бесконечности.

    Второй пример — короткий чат: 1575 больше исходных 1000, координация
    сожрала больше, чем дала параллельность.

    Использует amdahl_time.
    """
    return amdahl_time(t_serial, p, n) + c * n


def hogwild_speedup(t_serial, p, n, c):
    """Во сколько раз Hogwild! быстрее одинокого воркера без координации.

    hogwild_speedup(10000, 0.7, 4, 200)  ->  примерно 1.80
    hogwild_speedup(1000, 0.3, 4, 200)   ->  примерно 0.63

    Меньше единицы — значит стало ХУЖЕ, и это нормальный, часто
    встречающийся исход. Знаменатель — время Hogwild!, числитель — честное
    t_serial без всякой координации.

    Использует hogwild_time.
    """
    return t_serial / hogwild_time(t_serial, p, n, c)


def best_worker_count(t_serial, p, c, max_workers):
    """Сколько воркеров запускать. Число от 1 до max_workers.

    best_worker_count(10000, 0.7, 200, 16)  ->  6
    best_worker_count(1000, 0.3, 500, 8)    ->  1

    Перебор: минимизируем hogwild_time. При равенстве берём МЕНЬШЕЕ число
    воркеров — лишние процессы это лишняя VRAM под активации, даже если
    время то же.

    Формулой оптимум тоже берётся (производная по n), но перебор честнее:
    воркеров всё равно целое число, а модель стоимости в реальности не
    гладкая.

    Использует hogwild_time.
    """
    best_n, best_t = 1, hogwild_time(t_serial, p, 1, c)
    for n in range(2, max_workers + 1):
        t = hogwild_time(t_serial, p, n, c)
        if t < best_t:
            best_n, best_t = n, t
    return best_n


def visible_counts(cache, num_categories, lag=0):
    """Что воркер видит в общем кеше: токенов на категорию. Список счётчиков.

    visible_counts([(0, 0, 1, 0), (0, 1, 1, 1)], 3)     ->  [0, 2, 0]
    visible_counts([(0, 0, 1, 0), (0, 1, 1, 1)], 3, 1)  ->  [0, 1, 0]

    lag — сколько последних записей ещё не долетело до этого воркера.
    lag = 0 значит мгновенную видимость, ради которой кеш и делают общим.

    Ловушка: lag больше длины кеша — это не ошибка, это «воркер только что
    стартовал». Срез должен давать пустой список, а не считать с конца.
    """
    visible = cache[: len(cache) - lag] if lag > 0 else cache
    counts = [0] * num_categories
    for _, _, category, _ in visible:
        counts[category] += 1
    return counts


def next_category(counts, coordination_weight):
    """Какую подцель берёт воркер. Индекс категории.

    next_category([0, 0, 0], 1.0)  ->  0
    next_category([2, 0, 0], 1.0)  ->  1
    next_category([2, 0, 0], 0.0)  ->  0

    Оценка категории: -coordination_weight * counts[i] - PREFERENCE_GAP * i.
    Первое слагаемое — «этим уже занимаются, пойду в другое место», второе —
    врождённое предпочтение модели. Побеждает максимум, ничьи — по меньшему
    индексу.

    coordination_weight = 0 отключает чтение кеша: воркер всегда лезет в
    категорию 0. Именно так ведут себя модели без способности рассуждать —
    и именно поэтому N копий такой модели делают работу одного.
    """
    best_index, best_score = 0, None
    for i, count in enumerate(counts):
        score = -coordination_weight * count - PREFERENCE_GAP * i
        if best_score is None or score > best_score:
            best_index, best_score = i, score
    return best_index


def run_hogwild(n_workers, rounds, num_categories, coordination_weight=1.0, lag=0):
    """Прогон Hogwild!. Общий кеш — список записей (round, worker, category, index).

    len(run_hogwild(2, 20, 4))  ->  40
    run_hogwild(1, 2, 2)        ->  [(0, 0, 0, 0), (1, 0, 1, 0)]

    В каждом раунде воркеры пишут по очереди — 0, 1, ..., n-1 — и каждый
    видит всё, что написано до него (за вычетом lag). Один раунд это одно
    wall-time окно, поэтому n воркеров за rounds раундов дают n * rounds
    записей, а один воркер — rounds записей. Сравнивать честно можно только
    при одинаковых rounds.

    index у записи — это счётчик видимых токенов категории на момент
    записи. Два воркера, увидевшие одинаковую картину, напишут ОДИН И ТОТ
    ЖЕ (category, index): работа продублирована. Это и есть основной
    провальный режим Hogwild!.

    Использует visible_counts и next_category.
    """
    cache = []
    for round_index in range(rounds):
        for worker in range(n_workers):
            counts = visible_counts(cache, num_categories, lag)
            category = next_category(counts, coordination_weight)
            cache.append((round_index, worker, category, counts[category]))
    return cache


def useful_work(cache, quota):
    """Сколько РАЗНОЙ полезной работы сделано. Число токенов.

    useful_work([(0, 0, 0, 0), (0, 1, 0, 0)], 10)  ->  1
    useful_work([(0, 0, 0, 0), (0, 1, 1, 0)], 10)  ->  2
    useful_work([(0, 0, 0, 5)], 3)                 ->  0

    Полезен токен, у которого пара (category, index) встречается впервые и
    index меньше quota: подцель считается закрытой после quota токенов, всё
    сверх — переливание из пустого в порожнее.

    Первый пример — два воркера написали одно и то же: работы на единицу,
    а токенов потрачено два. Именно эту разницу и меряют, когда говорят,
    что «speedup обвалился».
    """
    return len({(category, index) for _, _, category, index in cache if index < quota})
