def q_step(x_prev, beta_t, noise):
    """Один марковский шаг вперёд: q(x_t | x_{t-1}).

        x_t = sqrt(1 - beta_t) * x_prev + sqrt(beta_t) * noise

    x_prev и noise — списки одной длины (сплющенная картинка), результат — список.

    q_step([1.0], 0.0, [5.0])   ->  [1.0]   (beta = 0: шум не подмешался)
    q_step([1.0], 1.0, [5.0])   ->  [5.0]   (beta = 1: от сигнала ничего)
    q_step([2.0], 0.75, [0.0])  ->  [1.0]   (sqrt(0.25) * 2)

    Коэффициенты не случайны: sqrt(1-beta)^2 + sqrt(beta)^2 = 1, поэтому шаг
    сохраняет дисперсию. Без этого за тысячу шагов числа улетели бы в космос.
    """
