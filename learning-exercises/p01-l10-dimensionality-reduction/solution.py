"""
Снижение размерности — эталон.

Открывай ПОСЛЕ своих зелёных тестов.
"""

import math


def column_means(X):
    """Среднее по каждому признаку. X — список строк-наблюдений.

    column_means([[1, 10], [3, 20]])  ->  [2.0, 15.0]

    Усреднять надо ПО СТОЛБЦАМ (по наблюдениям), а не по строкам:
    строка — это один объект, столбец — один признак.
    """
    n = len(X)
    # zip(*X) отдаёт столбцы — не нужно ни индексов, ни знания числа признаков
    return [sum(col) / n for col in zip(*X)]


def center(X):
    """Вычесть из каждого признака его среднее. PCA начинается отсюда.

    center([[1, 10], [3, 20]])  ->  [[-1.0, -5.0], [1.0, 5.0]]

    После центрирования среднее каждого столбца равно нулю. Без этого шага
    первая «главная компонента» просто укажет из начала координат
    на центр облака и никакой структуры не покажет.

    Входную матрицу не портить: возвращай новую.
    """
    mu = column_means(X)
    return [[value - m for value, m in zip(row, mu)] for row in X]


def covariance_matrix(X):
    """Ковариационная матрица признаков (несмещённая, делитель n - 1).

    covariance_matrix([[1, 1], [2, 2], [3, 3]])  ->  [[1.0, 1.0], [1.0, 1.0]]

    Элемент (i, j) — насколько согласованно ходят признаки i и j.
    На диагонали стоят обычные дисперсии.

    Матрица симметрична: cov(i, j) = cov(j, i). Центрируй через center,
    не повторяй вычитание среднего руками.
    """
    C = center(X)
    n = len(C)
    d = len(C[0])
    # держим столбцы отдельно: так внутренний цикл — простое скалярное
    # произведение двух списков, без обращения по двум индексам
    cols = [list(col) for col in zip(*C)]
    denom = n - 1
    return [
        [sum(a * b for a, b in zip(cols[i], cols[j])) / denom for j in range(d)]
        for i in range(d)
    ]


def power_iteration(A, iters=500, tol=1e-12):
    """Степенной метод: доминирующая по модулю собственная пара симметричной матрицы.

    Возвращает (eigenvalue, unit_eigenvector).

    power_iteration([[2, 0], [0, 3]])  ->  (3.0, [0.0, 1.0])
    power_iteration([[5, 0], [0, 1]])  ->  (5.0, [1.0, 0.0])
    power_iteration([[-5, 0], [0, 2]]) ->  (-5.0, [1.0, 0.0])

    Идея: умножай вектор на A и нормируй. Направление с наибольшим
    МОДУЛЕМ собственного числа побеждает остальные экспоненциально быстро.
    Собственное число потом бери как v @ A @ v (отношение Рэлея).

    Это не обязательно наибольшее алгебраически собственное число: если
    отрицательное значение имеет больший модуль, метод вернёт его. Для PCA
    матрица ковариации положительно полуопределена, поэтому различия нет.

    Две ловушки. Знак вектора не определён: [1, 0] и [-1, 0] одинаково
    верны, тесты обязаны это учитывать. И если A обнуляет вектор (нулевая
    матрица после дефляции), нормировать нечего — возвращай (0.0, нули).
    """
    n = len(A)
    # стартовый вектор нарочно неравномерный: [1, 1, ...] может оказаться
    # ровно ортогонален искомому направлению и метод не сдвинется
    v = [1.0 / (i + 1) for i in range(n)]
    norm = math.sqrt(sum(x * x for x in v))
    v = [x / norm for x in v]

    for _ in range(iters):
        w = [sum(A[i][j] * v[j] for j in range(n)) for i in range(n)]
        norm = math.sqrt(sum(x * x for x in w))
        if norm < tol:
            return 0.0, [0.0] * n
        w = [x / norm for x in w]
        # Для отрицательного собственного числа знак меняется на каждом шаге;
        # v и -v задают одно направление, поэтому проверяем оба варианта.
        same = sum(abs(a - b) for a, b in zip(w, v))
        opposite = sum(abs(a + b) for a, b in zip(w, v))
        if min(same, opposite) < tol:
            v = w
            break
        v = w

    Av = [sum(A[i][j] * v[j] for j in range(n)) for i in range(n)]
    eigenvalue = sum(a * b for a, b in zip(v, Av))
    return eigenvalue, v


def top_components(A, k, iters=500):
    """k главных собственных пар симметричной матрицы, по убыванию собственных чисел.

    Возвращает список пар (eigenvalue, eigenvector).

    top_components([[2, 0], [0, 3]], 1)  ->  [(3.0, [0.0, 1.0])]
    top_components([[2, 0], [0, 3]], 2)  ->  [(3.0, ...), (2.0, ...)]

    Метод дефляции: нашли пару (lam, v) — вычли из матрицы lam * v * v^T,
    и следующий запуск степенного метода найдёт уже вторую по величине.
    Собственные векторы симметричной матрицы ортогональны, поэтому
    вычитание не портит остальные направления.

    В ковариационной матрице собственные числа неотрицательны, а вектор —
    это направление максимального разброса данных.
    """
    n = len(A)
    # копия: дефляция портит матрицу, а вызывающему она ещё нужна
    M = [row[:] for row in A]
    pairs = []
    for _ in range(k):
        value, vector = power_iteration(M, iters)
        pairs.append((value, vector))
        M = [
            [M[i][j] - value * vector[i] * vector[j] for j in range(n)]
            for i in range(n)
        ]
    return pairs


def explained_variance_ratio(A, k):
    """Доля общей дисперсии, которую забирает каждая из k главных компонент.

    explained_variance_ratio([[4, 0], [0, 1]], 2)  ->  [0.8, 0.2]
    explained_variance_ratio([[4, 0], [0, 1]], 1)  ->  [0.8]

    Полная дисперсия — это след матрицы (сумма диагонали), он же сумма ВСЕХ
    собственных чисел. Считать все компоненты ради знаменателя не нужно.

    Список всегда убывает. Накопленная сумма 0.95 — стандартный ответ на
    вопрос «сколько компонент оставить».
    """
    total = sum(A[i][i] for i in range(len(A)))
    return [value / total for value, _ in top_components(A, k)]


def project(X, components):
    """Проекция наблюдений на главные направления: новые координаты.

    components — список векторов (без собственных чисел).

    project([[1, 0], [-1, 0]], [[1.0, 0.0]])  ->  [[1.0], [-1.0]]

    Каждая строка результата — k скалярных произведений центрированной
    строки на компоненты. Ловушка: центрировать надо ОБЯЗАТЕЛЬНО и теми же
    средними, иначе координаты уедут на постоянный сдвиг.
    """
    C = center(X)
    return [[sum(a * b for a, b in zip(row, comp)) for comp in components] for row in C]


def reconstruction_error(X, k):
    """Средний квадрат ошибки восстановления после сжатия до k компонент.

    reconstruction_error([[1, 0], [-1, 0], [2, 0], [-2, 0]], 1)  ->  0.0
    reconstruction_error(любые данные, k = числу признаков)      ->  ~0.0

    Схема: центрировать -> спроецировать на k компонент -> вернуть обратно
    (сумма scores[j] * component[j]) -> сравнить с центрированным оригиналом.

    Ошибка убывает с ростом k и равна сумме ОТБРОШЕННЫХ собственных чисел
    (с точностью до делителя). На этом же строится поиск аномалий: объект
    с большой ошибкой восстановления не лежит в найденном подпространстве.
    """
    pairs = top_components(covariance_matrix(X), k)
    components = [vector for _, vector in pairs]
    C = center(X)
    scores = project(X, components)

    total = 0.0
    count = 0
    for original, score in zip(C, scores):
        # восстановление: линейная комбинация компонент с весами-координатами
        rebuilt = [
            sum(s * comp[j] for s, comp in zip(score, components))
            for j in range(len(original))
        ]
        for a, b in zip(original, rebuilt):
            total += (a - b) ** 2
            count += 1
    return total / count
