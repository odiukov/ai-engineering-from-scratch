import math


def back_substitution(U, y):
    """Решает верхнетреугольную систему U x = y, идя снизу вверх.

    back_substitution([[2, 1], [0, 3]], [5, 9])  ->  [1.0, 3.0]
    back_substitution([[1, 0], [0, 1]], [4, 7])  ->  [4.0, 7.0]

    U — квадратная матрица (список списков). Всё, что ниже диагонали, не
    смотрим: там по договорённости нули, и что бы туда ни положили, ответ
    меняться не должен.

    Порядок важен: последняя строка даёт x[n-1] сразу, а каждая следующая
    вверх уже знает все x правее себя. Сверху вниз это не решается.
    Если на диагонали ноль — единственного решения нет, брось ValueError.

    В AI это второй шаг любого решателя: Gaussian elimination, LU и
    Cholesky нужны ровно затем, чтобы свести задачу к треугольной.
    """
    n = len(y)
    x = [0.0] * n
    # снизу вверх: к моменту строки i все x[i+1:] уже посчитаны
    for i in range(n - 1, -1, -1):
        if abs(U[i][i]) < 1e-12:
            raise ValueError(f"нулевой pivot в строке {i}: решение не единственно")
        # сумму накапливаем обычным циклом, а не срезами и zip:
        # срез копирует хвост строки, и на n в сотни это заметная лишняя работа
        s = y[i]
        row = U[i]
        for j in range(i + 1, n):
            s -= row[j] * x[j]
        x[i] = s / row[i]
    return x  # O(n^2): каждая строка стоит своей длины


def forward_substitution(L, b):
    """Решает нижнетреугольную систему L y = b, идя сверху вниз.

    forward_substitution([[2, 0], [1, 3]], [4, 11])  ->  [2.0, 3.0]
    forward_substitution([[1, 0], [0, 1]], [4, 7])   ->  [4.0, 7.0]

    Зеркало back_substitution: первая строка содержит одну неизвестную,
    дальше каждая строка знает всё, что левее. Всё, что ВЫШЕ диагонали,
    игнорируем — там нули по договорённости.

    Нулевой элемент на диагонали — ValueError, как и в back_substitution.

    Половина решения через LU и Cholesky — это ровно этот проход:
    сначала L y = b сверху вниз, потом U x = y снизу вверх.
    """
    n = len(b)
    y = [0.0] * n
    # сверху вниз: к моменту строки i все y[:i] уже посчитаны
    for i in range(n):
        if abs(L[i][i]) < 1e-12:
            raise ValueError(f"нулевой pivot в строке {i}: решение не единственно")
        s = b[i]
        row = L[i]
        for j in range(i):
            s -= row[j] * y[j]
        y[i] = s / row[i]
    return y  # O(n^2), как и back_substitution


def gaussian_elimination(A, b):
    """Решает Ax = b методом Гаусса с partial pivoting. Возвращает список x.

    gaussian_elimination([[2, 1, 1], [4, 3, 3], [2, 3, 1]], [8, 20, 12])
        ->  [2.0, 2.0, 2.0]
    gaussian_elimination([[0, 1], [1, 0]], [2, 3])  ->  [3.0, 2.0]

    Схема: для каждого столбца k выбрать строку с наибольшим по модулю
    элементом в этом столбце (это и есть partial pivoting), поставить её на
    место k, вычесть её кратные из всех строк ниже. Получится верхний
    треугольник — дальше зови back_substitution, а не переписывай её.

    Две ловушки. Первая: без выбора pivot нулевой элемент на диагонали
    (второй пример выше) роняет решение делением на ноль, а маленький —
    раздувает ошибку округления. Вторая: A и b трогать нельзя, работай с
    копией, вызывающий вправе пользоваться своей матрицей дальше.

    Если весь столбец под pivot нулевой — матрица вырождена, ValueError.

    O(n^3). Это цена одного решения; LU платит её один раз и потом решает
    новые b за O(n^2).
    """
    n = len(b)
    # расширенная матрица [A | b] своей копией: вход остаётся нетронутым.
    # Одна копия на весь вызов — O(n^2) памяти против O(n^3) арифметики,
    # то есть по сравнению с самим исключением это бесплатно
    M = [[float(v) for v in A[i]] + [float(b[i])] for i in range(n)]

    for k in range(n):
        # partial pivoting: не украшение, а единственное, что держит
        # множитель m по модулю не больше единицы. Большой m умножает
        # ошибки округления всей опорной строки и заносит их в остальные
        piv = max(range(k, n), key=lambda i: abs(M[i][k]))
        if abs(M[piv][k]) < 1e-12:
            raise ValueError(f"матрица вырождена: пустой столбец {k}")
        if piv != k:
            M[k], M[piv] = M[piv], M[k]  # swap ссылок, строки не копируются

        row_k = M[k]
        pivot = row_k[k]
        for i in range(k + 1, n):
            row_i = M[i]
            m = row_i[k] / pivot
            if m == 0.0:
                continue  # строка уже обнулена, экономим O(n) на ней
            # идём с j=k, а не с нуля: слева от k уже нули в обеих строках
            for j in range(k, n + 1):
                row_i[j] -= m * row_k[j]

    # back_substitution смотрит только U[i][i] и U[i][j] при j < n,
    # так что лишний столбец b ей не мешает и вырезать его не нужно
    return back_substitution(M, [M[i][n] for i in range(n)])


def cholesky(A):
    """Раскладывает симметричную положительно определённую A на L, где A = L L^T.

    cholesky([[4, 2], [2, 5]])  ->  [[2.0, 0.0], [1.0, 2.0]]
    cholesky([[4, 0], [0, 9]])  ->  [[2.0, 0.0], [0.0, 3.0]]

    L — нижнетреугольная, выше диагонали строго нули (их надо положить
    явно, а не оставить «как получится»).

    Формулы:
      L[i][i] = sqrt(A[i][i] - sum(L[i][k]^2       for k < i))
      L[i][j] = (A[i][j] - sum(L[i][k]*L[j][k] for k < j)) / L[j][j]   при i > j

    Две ловушки, и обе про вход. Матрица обязана быть симметричной: на
    несимметричной формулы молча дадут L, у которого L L^T не равно A, —
    проверь симметрию сама и брось ValueError. И если под корнем оказалось
    неположительное число, матрица не положительно определена — тоже
    ValueError, а не math.sqrt с NaN.

    В AI это рабочая лошадь: ковариационные матрицы, kernel-матрица
    гауссовских процессов и X^T X + lambda*I из ridge — все SPD, и все
    решаются через Cholesky вдвое быстрее LU.
    """
    n = len(A)
    # симметрию проверяем заранее и целиком: дешёвые O(n^2) против
    # молчаливо неверного ответа, который вылезет через три функции
    for i in range(n):
        for j in range(i):
            if abs(A[i][j] - A[j][i]) > 1e-9 * (1.0 + abs(A[i][j])):
                raise ValueError(f"матрица не симметрична: A[{i}][{j}] != A[{j}][{i}]")

    L = [[0.0] * n for _ in range(n)]
    for i in range(n):
        Li = L[i]
        for j in range(i + 1):
            Lj = L[j]
            # скалярное произведение уже посчитанных кусков двух строк L
            s = float(A[i][j])
            for k in range(j):
                s -= Li[k] * Lj[k]
            if i == j:
                if s <= 0.0:
                    raise ValueError(f"матрица не положительно определена (строка {i})")
                Li[j] = math.sqrt(s)
            else:
                Li[j] = s / Lj[j]
    # n^3/6 умножений — ровно вдвое меньше, чем у Гаусса, потому что
    # считаем только нижний треугольник и симметрию не пересчитываем
    return L


def solve_cholesky(A, b):
    """Решает Ax = b для симметричной положительно определённой A через Cholesky.

    solve_cholesky([[4, 0], [0, 9]], [8, 18])   ->  [2.0, 2.0]
    solve_cholesky([[4, 2], [2, 5]], [10, 14])  ->  [1.375, 2.25]

    Идея в два шага: A = L L^T, значит L (L^T x) = b. Сначала forward_substitution
    даёт y из L y = b, потом back_substitution даёт x из L^T x = y.
    Никакой новой арифметики — только три уже написанные функции.

    Ловушка: back_substitution нужен именно L^T, а не L. Транспонировать
    придётся явно, «мысленно» она это не сделает.

    Если A не SPD, ValueError прилетит из cholesky — это нормально.
    """
    L = cholesky(A)
    y = forward_substitution(L, b)
    n = len(L)
    # явная транспонированная копия: O(n^2) на фоне O(n^3) факторизации
    # ничего не стоит, а читается честнее, чем решатель с флагом «наоборот»
    Lt = [[L[j][i] for j in range(n)] for i in range(n)]
    return back_substitution(Lt, y)


def normal_equations(A, b):
    """Строит нормальные уравнения: возвращает пару (A^T A, A^T b).

    normal_equations([[1, 1], [1, 2], [1, 3], [1, 4]], [3, 5, 6, 8])
        ->  ([[4.0, 10.0], [10.0, 30.0]], [22.0, 63.0])
    normal_equations([[1, 0], [0, 1]], [5, 7])
        ->  ([[1.0, 0.0], [0.0, 1.0]], [5.0, 7.0])

    A — m строк на n столбцов (данных больше, чем неизвестных), b — длины m.
    A^T A всегда n x n и всегда симметрична; A^T b — длины n.

    Ловушка в порядке индексов: (A^T A)[i][j] = sum(A[k][i]*A[k][j] for k),
    суммирование идёт по СТРОКАМ A, а i и j — номера столбцов. Перепутать
    легко, а на квадратной A ошибка не видна: проверяй на прямоугольной.

    Отсюда растёт вся линейная регрессия: минимум ||Ax - b||^2 достигается
    там, где A^T A x = A^T b.
    """
    m = len(A)
    n = len(A[0])
    AtA = [[0.0] * n for _ in range(n)]
    Atb = [0.0] * n
    # внешний цикл по строкам A: так каждую строку читаем один раз,
    # а не n^2 раз выдёргиваем отдельные элементы по столбцам
    for k in range(m):
        row = A[k]
        bk = b[k]
        for i in range(n):
            r = row[i]
            if r == 0.0:
                continue  # нули в данных встречаются часто (one-hot), пропуск даром
            Atb[i] += r * bk
            AtA_i = AtA[i]
            # только верхний треугольник: нижний — его зеркало
            for j in range(i, n):
                AtA_i[j] += r * row[j]
    # зеркалим. Копирование, а не пересчёт: заодно симметрия получается
    # ТОЧНОЙ побитово, и cholesky ниже по цепочке не придерётся
    for i in range(n):
        for j in range(i):
            AtA[i][j] = AtA[j][i]
    return AtA, Atb  # O(m*n^2/2)


def least_squares(A, b):
    """Решение по методу наименьших квадратов: x, минимизирующий ||Ax - b||^2.

    least_squares([[1, 1], [1, 2], [1, 3], [1, 4]], [3, 5, 6, 8])
        ->  [1.5, 1.6]   (свободный член и наклон прямой)
    least_squares([[1, 0], [0, 1]], [5, 7])  ->  [5.0, 7.0]

    Собирается из готового: normal_equations даёт A^T A и A^T b,
    gaussian_elimination их решает. Своей арифметики тут нет вообще.

    Ловушка: если столбцы A линейно зависимы (например, один столбец —
    копия другого), то A^T A вырождена и решения нет — прилетит ValueError
    из gaussian_elimination. Это не баг, а сигнал: признаки коллинеарны,
    лечится регуляризацией (см. ridge_regression).

    Это и есть закрытая формула линейной регрессии, та самая, что считает
    LinearRegression.fit(): w = (X^T X)^(-1) X^T y.
    """
    AtA, Atb = normal_equations(A, b)
    return gaussian_elimination(AtA, Atb)


def ridge_regression(A, b, lam):
    """Ridge: решает (A^T A + lam*I) x = A^T b. При lam=0 это least_squares.

    ridge_regression([[1, 1], [1, 1]], [2, 2], 1.0)  ->  [0.8, 0.8]
    ridge_regression([[1, 1], [1, 2], [1, 3], [1, 4]], [3, 5, 6, 8], 0.0)
        ->  [1.5, 1.6]

    Первый пример важен: столбцы A одинаковы, least_squares на нём падает,
    а ridge решает — lam на диагонали вытаскивает матрицу из вырождения.

    Ловушка: lam добавляется ТОЛЬКО к диагонали A^T A (то есть lam*I),
    а к A^T b не добавляется ничего. И прибавлять надо к своей копии,
    вход A портить нельзя.

    При lam > 0 матрица A^T A + lam*I гарантированно симметрична и
    положительно определена, поэтому решать её правильно через
    solve_cholesky, а не Гауссом: вдвое быстрее и устойчивее.

    Чем больше lam, тем сильнее веса стянуты к нулю — так регуляризация
    борется с переобучением и с коллинеарными признаками разом.
    """
    AtA, Atb = normal_equations(A, b)
    n = len(Atb)
    # AtA — свежий локальный список из normal_equations, править его можно;
    # правим на месте, чтобы не плодить ещё одну n x n копию
    for i in range(n):
        AtA[i][i] += lam
    # lam > 0 делает матрицу строго положительно определённой,
    # так что Cholesky не упрётся в неположительный корень
    return solve_cholesky(AtA, Atb)
