"""
Векторы, матрицы и операции — эталон.

Открывай ПОСЛЕ своих зелёных тестов. Это не единственно верный вариант,
а один из хороших: сравни со своим и разберись, где разошлись.
"""


def transpose(M):
    """Транспонирование: строки становятся столбцами.

    transpose([[1, 2, 3], [4, 5, 6]])  ->  [[1, 4], [2, 5], [3, 6]]

    Матрица m x n превращается в n x m.
    """
    # zip(*M) разбирает строки на позиционные аргументы и склеивает их
    # поэлементно — это и есть транспонирование
    return [list(col) for col in zip(*M)]


def matmul(A, B):
    """Умножение матриц: A размера m x k на B размера k x n даёт m x n.

    matmul([[1, 2], [3, 4]], [[1, 0], [0, 1]])  ->  [[1, 2], [3, 4]]
    matmul([[1, 2]], [[3], [4]])                ->  [[11]]

    Элемент (i, j) результата — скалярное произведение i-й строки A
    на j-й столбец B.
    """
    # транспонируем B один раз, чтобы столбцы стали строками и внутренний
    # цикл шёл по непрерывной строке, а не лазил по индексам
    Bt = transpose(B)
    return [[sum(a * b for a, b in zip(row, col)) for col in Bt] for row in A]


def identity(n):
    """Единичная матрица n x n: единицы по диагонали, нули везде ещё.

    identity(2)  ->  [[1, 0], [0, 1]]

    Умножение на неё ничего не меняет — это "1" в мире матриц.
    """
    return [[1 if i == j else 0 for j in range(n)] for i in range(n)]


def trace(M):
    """След: сумма элементов на главной диагонали. Матрица квадратная.

    trace([[1, 2], [3, 4]])  ->  5

    След равен сумме собственных значений — пригодится в уроке про eigen.
    """
    # enumerate вместо range(len(M)) — сразу и индекс, и строка
    return sum(row[i] for i, row in enumerate(M))


def is_symmetric(M):
    """Симметрична ли матрица: равна ли она своей транспонированной.

    is_symmetric([[1, 2], [2, 1]])  ->  True
    is_symmetric([[1, 2], [3, 1]])  ->  False

    Симметричные матрицы важны: у них всегда вещественные собственные
    значения. Матрица ковариации — симметрична.
    """
    return M == transpose(M)


def hadamard(A, B):
    """Поэлементное умножение (произведение Адамара), НЕ матричное.

    hadamard([[1, 2], [3, 4]], [[10, 10], [10, 10]])  ->  [[10, 20], [30, 40]]

    Именно так работают маски внимания и дропаут: поэлементно, не matmul.
    """
    return [[a * b for a, b in zip(ra, rb)] for ra, rb in zip(A, B)]
