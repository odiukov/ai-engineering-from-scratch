"""
Теория информации — эталон.

Открывай ПОСЛЕ своих зелёных тестов.
"""

import math


def information_content(p, base=2):
    """Информация события с вероятностью p: сколько «удивления» оно несёт.

    information_content(0.5)     ->  1.0    (один бит, честная монета)
    information_content(1.0)     ->  0.0    (достоверное не удивляет)
    information_content(0.001)   ->  9.965...

    I(x) = -log(p) / log(base). base=2 даёт биты, base=e — наты.

    Ловушка: p = 0 — это math.log(0) и ValueError. Событие нулевой
    вероятности несёт бесконечное удивление, так и возвращаем math.inf.
    """
    if p <= 0:
        return math.inf
    return -math.log(p) / math.log(base)


def entropy(probs, base=2):
    """Энтропия распределения: среднее удивление по всем исходам.

    entropy([0.5, 0.5])        ->  1.0     (максимум для двух исходов)
    entropy([0.99, 0.01])      ->  0.0807...
    entropy([1.0, 0.0])        ->  0.0     (исход предрешён)
    entropy([1/6] * 6)         ->  2.585...

    H(P) = сумма p * I(p). Ловушка: слагаемые с p = 0 надо ПРОПУСКАТЬ,
    иначе получишь 0 * inf = nan. По пределу 0 * log(0) = 0.

    Энтропия — нижняя граница сжатия: короче неё закодировать нельзя.
    """
    return sum(p * information_content(p, base) for p in probs if p > 0)


def cross_entropy(p, q, base=2):
    """Кросс-энтропия: среднее удивление, когда события из P кодируешь по Q.

    cross_entropy([1.0, 0.0], [0.5, 0.5])   ->  1.0
    cross_entropy([0.5, 0.5], [0.5, 0.5])   ->  1.0   (совпало — это энтропия)
    cross_entropy([0.7, 0.3], [0.1, 0.9])   ->  2.3709...

    H(P, Q) = -сумма p(x) * log q(x). Ловушка: если q(x) = 0 там, где
    p(x) > 0, модель считает реальное событие невозможным — цена
    бесконечна, возвращаем math.inf. А вот q(x) = 0 при p(x) = 0
    безобиден, такое слагаемое просто пропускается.

    Несимметрична: аргументы местами не меняй, P — правда, Q — модель.
    """
    total = 0.0
    for pi, qi in zip(p, q):
        if pi > 0:
            if qi <= 0:
                return math.inf
            total += pi * information_content(qi, base)
    return total


def kl_divergence(p, q, base=2):
    """KL-дивергенция: сколько лишнего платишь за кодирование P по Q.

    kl_divergence([0.5, 0.5], [0.5, 0.5])   ->  0.0   (и только тут ноль)
    kl_divergence([0.7, 0.3], [0.6, 0.4])   ->  0.0311...
    kl_divergence([0.7, 0.3], [0.1, 0.9])   ->  1.4896...

    D(P || Q) = H(P, Q) - H(P). Считай именно так, через уже написанные
    функции, а не отдельной формулой с логарифмом отношения.

    Всегда >= 0 и НЕ симметрична — метрикой расстояния не является.
    Энтропия правды при обучении постоянна, поэтому минимизировать
    кросс-энтропию и минимизировать KL — одно и то же.
    """
    return cross_entropy(p, q, base) - entropy(p, base)


def joint_entropy(joint, base=2):
    """Энтропия совместного распределения, заданного таблицей joint[i][j].

    joint_entropy([[0.25, 0.25], [0.25, 0.25]])  ->  2.0
    joint_entropy([[0.5, 0.0], [0.0, 0.5]])      ->  1.0

    Это обычная энтропия по всем клеткам таблицы разом — разверни таблицу
    в плоский список и позови entropy.

    H(X, Y) <= H(X) + H(Y), равенство только при независимости.
    """
    flat = [cell for row in joint for cell in row]
    return entropy(flat, base)


def conditional_entropy(joint, base=2):
    """Условная энтропия H(Y|X): что осталось неизвестным про Y после знания X.

    Строки таблицы — исходы X, столбцы — исходы Y.

    conditional_entropy([[0.25, 0.25], [0.25, 0.25]])  ->  1.0  (X не помог)
    conditional_entropy([[0.5, 0.0], [0.0, 0.5]])      ->  0.0  (X решает всё)

    H(Y|X) = H(X, Y) - H(X), где H(X) — энтропия маргинала по строкам.

    Всегда 0 <= H(Y|X) <= H(Y). Дерево решений на каждом узле выбирает
    признак X, который минимизирует именно эту величину.
    """
    px = [sum(row) for row in joint]
    return joint_entropy(joint, base) - entropy(px, base)


def mutual_information(joint, base=2):
    """Взаимная информация I(X;Y): насколько знание X снижает незнание Y.

    mutual_information([[0.25, 0.25], [0.25, 0.25]])  ->  0.0  (независимы)
    mutual_information([[0.45, 0.05], [0.05, 0.45]])  ->  0.5310...
    mutual_information([[0.5, 0.0], [0.0, 0.5]])      ->  1.0  (X = Y)

    I(X;Y) = H(Y) - H(Y|X). Опирайся на conditional_entropy.

    Симметрична, всегда >= 0, ноль ровно при независимости. Ловит любую
    зависимость, а не только линейную, — потому и используется для
    отбора признаков вместо корреляции.
    """
    py = [sum(col) for col in zip(*joint)]
    return entropy(py, base) - conditional_entropy(joint, base)


def perplexity(p, q, base=2):
    """Перплексия: во скольких равновероятных вариантах модель «путается».

    perplexity([1.0, 0.0], [0.5, 0.5])           ->  2.0
    perplexity([1.0, 0.0], [1.0, 0.0])           ->  1.0   (полная уверенность)
    perplexity([0.25] * 4, [0.25] * 4)           ->  4.0

    Perplexity = base ** H(P, Q). Основание степени обязано совпадать
    с основанием логарифма в кросс-энтропии, иначе число будет бессмысленным.

    Языковая модель с перплексией 30 выбирает следующий токен так, будто
    тычет наугад в 30 одинаково вероятных вариантов. Меньше — лучше.
    """
    return base ** cross_entropy(p, q, base)
