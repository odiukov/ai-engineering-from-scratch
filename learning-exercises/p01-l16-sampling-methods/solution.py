"""
Методы сэмплирования — эталон.

Открывай ПОСЛЕ своих зелёных тестов.
"""

import math


def softmax_with_temperature(logits, temperature=1.0):
    """Softmax по логитам с температурой: поделить на T, взять exp, нормировать.

    softmax_with_temperature([0.0, 0.0])       ->  [0.5, 0.5]
    softmax_with_temperature([2.0, 1.0])       ->  [0.7310585, 0.2689414]
    softmax_with_temperature([2.0, 1.0], 0.5)  ->  [0.8807970, 0.1192029]

    T < 1 заостряет распределение (модель увереннее, разнообразия меньше),
    T > 1 сглаживает. Сумма результата всегда 1 при любой T.

    Ловушка первая: exp(1000) — это OverflowError. Вычти максимум из всех
    масштабированных логитов: сумма долей от этого не меняется, а числа
    остаются в безопасном диапазоне.
    Ловушка вторая: T = 0 — деление на ноль. Здесь T <= 0 это ValueError
    (жадный argmax — отдельный режим, а не предел этой формулы).

    Это тот самый knob temperature, который крутят у любой LLM.
    """
    if temperature <= 0:
        raise ValueError("temperature должна быть строго больше нуля")
    scaled = [z / temperature for z in logits]
    # Сдвиг на максимум: после него exp(z - shift) <= 1, переполнения не будет
    # никогда. Математически это домножение числителя и знаменателя на
    # exp(-shift) — ответ тот же, а float остаётся в рабочем диапазоне.
    shift = max(scaled)
    exps = [math.exp(z - shift) for z in scaled]
    # exp(-inf) == 0.0, поэтому отфильтрованные top-k/top-p логиты честно
    # получают нулевую вероятность и не мешают нормировке.
    total = sum(exps)
    return [e / total for e in exps]


def sample_index(probs, rng):
    """Выбрать индекс по вектору вероятностей — дискретный inverse-CDF.

    rng — объект random.Random, передаётся явно, чтобы прогон был воспроизводим.

    sample_index([1.0, 0.0], random.Random(0))  ->  0  (при любом seed)
    sample_index([0.0, 1.0], random.Random(0))  ->  1  (при любом seed)
    sample_index([0.5, 0.5], random.Random(0))  ->  0 или 1

    Алгоритм: взять u = rng.random(), идти по списку, копить сумму, вернуть
    первый индекс, на котором накопленная сумма ПРЕВЫСИЛА u.

    Ловушка первая: сравнение `u <= acc` вместо `u < acc` вернёт индекс с
    нулевой вероятностью, если rng выдал ровно 0.0.
    Ловушка вторая: сумма probs из-за float бывает 0.9999999999 — цикл
    дойдёт до конца и не вернёт ничего. Нужен запасной выход.

    Так LLM превращает вектор вероятностей в конкретный токен.
    """
    u = rng.random()
    acc = 0.0
    # Один проход, O(n), одного вызова rng хватает на один сэмпл. Бинарный
    # поиск по заранее посчитанному CDF был бы O(log n), но окупается только
    # когда из одного и того же распределения тянут много раз подряд.
    for i, p in enumerate(probs):
        acc += p
        # строгое `<`: при p = 0.0 сумма не растёт, и такой индекс пропускается
        if u < acc:
            return i
    # сюда попадаем только из-за накопленной ошибки float — отдаём последний
    # ненулевой индекс, а не падаем
    for i in range(len(probs) - 1, -1, -1):
        if probs[i] > 0.0:
            return i
    return len(probs) - 1


def sample_exponential(lam, rng):
    """Сэмпл из экспоненциального распределения методом inverse CDF.

    CDF: F(x) = 1 - exp(-lam * x), значит x = -ln(1 - u) / lam.

    sample_exponential(1.0, random.Random(0))  ->  1.8606071
    sample_exponential(2.0, random.Random(0))  ->  0.9303035  (ровно вдвое меньше)
    среднее большого числа сэмплов             ->  1 / lam

    Ловушка первая: rng.random() возвращает u из [0, 1), то есть ровно 0.0
    возможен, а ln(0) роняет программу. Логарифм бери от (1 - u), не от u.
    Ловушка вторая: lam <= 0 — такого распределения нет, это ValueError.

    Экспоненциальное — время до следующего события; тот же inverse-CDF даёт
    сэмплы из любого распределения, у которого CDF обращается формулой.
    """
    if lam <= 0:
        raise ValueError("lam должна быть строго больше нуля")
    u = rng.random()
    # 1 - u лежит в (0, 1] — логарифм определён всегда. Вариант -ln(u)
    # распределён так же, но падает на u == 0.0, поэтому он тут не нужен.
    return -math.log(1.0 - u) / lam


def monte_carlo_pi(n, rng):
    """Оценка pi методом Монте-Карло: доля точек квадрата, попавших в круг.

    Бросаем n точек равномерно в [-1, 1] x [-1, 1], считаем долю тех, у
    которых x^2 + y^2 <= 1, и умножаем её на 4 — площадь квадрата.

    monte_carlo_pi(1000, random.Random(0))   ->  3.072
    monte_carlo_pi(20000, random.Random(0))  ->  3.137
    результат всегда кратен 4 / n            ->  это доля, умноженная на 4

    Ошибка падает как O(1 / sqrt(n)): чтобы добавить один верный знак, нужно
    в 100 раз больше точек. Зато скорость сходимости не зависит от размерности.

    Ловушка: n <= 0 — деление на ноль, это ValueError.

    Тем же приёмом считают интегралы без формулы: ожидание loss по данным,
    ELBO у VAE, отдачу политики в RL.
    """
    if n <= 0:
        raise ValueError("n должно быть положительным")
    inside = 0
    # Счётчик целых, деление одно в самом конце: складывать доли по одной —
    # это n операций с плавающей точкой и лишняя накопленная ошибка.
    for _ in range(n):
        x = 2.0 * rng.random() - 1.0
        y = 2.0 * rng.random() - 1.0
        # без sqrt: сравнение квадратов эквивалентно, а корень стоит дорого
        if x * x + y * y <= 1.0:
            inside += 1
    return 4.0 * inside / n


def rejection_sample(pdf, lo, hi, m, rng, max_tries=10000):
    """Rejection sampling: сэмпл из pdf на [lo, hi] через равномерное предложение.

    pdf — плотность (можно ненормированную), m — её верхняя граница на отрезке,
    то есть pdf(x) <= m для всех x из [lo, hi].
    Алгоритм: предложить x равномерно из [lo, hi], взять u из [0, 1), принять
    x при u * m < pdf(x), иначе пробовать заново.

    rejection_sample(lambda x: 1.0,   0.0, 1.0, 1.0, random.Random(0))  ->  0.8444218
    rejection_sample(lambda x: 2 * x, 0.0, 1.0, 2.0, random.Random(0))  ->  0.8444218
    доля принятых  ->  (площадь под pdf) / (m * (hi - lo))

    Ловушка первая: заниженное m ломает форму — такие x принимаются всегда,
    и распределение получается не то, которое просили.
    Ловушка вторая: если pdf нулевая на всём отрезке, цикл никогда не
    кончится. Ограничь число попыток и брось RuntimeError.
    Ловушка третья: m <= 0 — деление (или сравнение) теряет смысл, ValueError.

    В высокой размерности доля принятых падает экспоненциально — поэтому
    большие модели сэмплируют через MCMC, а не отбраковкой.
    """
    if m <= 0:
        raise ValueError("m должно быть положительным")
    if hi <= lo:
        raise ValueError("нужен непустой отрезок: hi > lo")
    width = hi - lo
    for _ in range(max_tries):
        x = lo + width * rng.random()
        u = rng.random()
        # сравниваем u * m < pdf(x), а не u < pdf(x) / m: одно умножение
        # вместо деления и никакого риска поделить на крошечное m
        if u * m < pdf(x):
            return x
    # молча вернуть последнее предложение нельзя — это было бы сэмплом из
    # предложения, а не из цели; лучше громко упасть
    raise RuntimeError("не удалось принять сэмпл за max_tries попыток")


def top_k_filter(logits, k):
    """Оставить k наибольших логитов, остальные заменить на -inf.

    top_k_filter([1.0, 3.0, 2.0], 2)  ->  [-inf, 3.0, 2.0]
    top_k_filter([1.0, 3.0, 2.0], 1)  ->  [-inf, 3.0, -inf]
    top_k_filter([1.0, 3.0, 2.0], 9)  ->  [1.0, 3.0, 2.0]  (k больше длины)

    Почему -inf, а не выбрасывание элементов: exp(-inf) = 0, значит после
    softmax токен получит ровно нулевую вероятность, а индексы остальных не
    съедут — позиция в списке это id токена в словаре.

    Ловушка первая: вход менять нельзя, возвращай новый список.
    Ловушка вторая: k <= 0 оставил бы пустой словарь — это ValueError.
    При равных логитах побеждает тот, что стоит раньше в списке.
    """
    if k <= 0:
        raise ValueError("k должно быть положительным")
    if k >= len(logits):
        # копия, а не сам список: вызывающий не должен получить псевдоним входа
        return list(logits)
    # сортируем индексы, а не значения: значение само по себе не скажет, куда
    # его вернуть. sorted стабилен, поэтому при равных логитах выигрывает
    # меньший индекс — поведение предсказуемое, а не «как повезёт».
    order = sorted(range(len(logits)), key=lambda i: logits[i], reverse=True)
    keep = set(order[:k])
    # set, а не list: проверка вхождения O(1), иначе получилось бы O(n * k)
    return [logits[i] if i in keep else -math.inf for i in range(len(logits))]


def top_p_filter(logits, p, temperature=1.0):
    """Nucleus (top-p): оставить минимальный набор токенов с массой не меньше p.

    Считаем softmax с температурой, сортируем по убыванию вероятности,
    набираем токены, пока накопленная масса не достигнет p. Не вошедшие
    логиты заменяем на -inf.

    top_p_filter([2.0, 1.0, 0.0], 0.5)  ->  [2.0, -inf, -inf]  (лидер даёт 0.665)
    top_p_filter([2.0, 1.0, 0.0], 0.7)  ->  [2.0, 1.0, -inf]   (0.665 + 0.245)
    top_p_filter([2.0, 1.0, 0.0], 1.0)  ->  [2.0, 1.0, 0.0]

    Ловушка первая: токен нужно добавлять в набор ДО проверки суммы. Если
    сначала проверять, а потом добавлять, то при p = 0.5 и лидере с
    вероятностью 0.99 набор окажется пустым и сэмплировать будет не из чего.
    Ловушка вторая: p вне (0, 1] — ValueError.
    Ловушка третья: вход не мутировать, вернуть новый список.

    В отличие от top-k размер набора подстраивается под уверенность модели:
    уверена — останется 2 токена, сомневается — 200.
    """
    if not 0.0 < p <= 1.0:
        raise ValueError("p должно лежать в (0, 1]")
    # вероятности берём той же температурой, с какой потом будем сэмплировать,
    # иначе отсечение считается не по тому распределению
    probs = softmax_with_temperature(logits, temperature)
    order = sorted(range(len(probs)), key=lambda i: probs[i], reverse=True)
    keep = set()
    cum = 0.0
    for i in order:
        # сначала добавляем, потом проверяем: набор никогда не будет пустым
        keep.add(i)
        cum += probs[i]
        if cum >= p:
            break
    return [logits[i] if i in keep else -math.inf for i in range(len(logits))]


def sample_token(logits, rng, temperature=1.0, top_k=None, top_p=None):
    """Декодер LLM целиком: температура + top-k + top-p, вернуть индекс токена.

    Порядок: сначала top-k, потом top-p по уже отфильтрованному, потом softmax
    с той же температурой и выбор индекса. None означает «фильтр выключен».

    sample_token([5.0, 4.0, -100.0], rng, top_k=1)   ->  0  (при любом seed)
    sample_token([0.0, 0.0], rng, temperature=2.0)   ->  0 или 1
    sample_token([5.0, 0.0], rng, temperature=0.01)  ->  практически всегда 0

    Собери из уже написанных функций, не переписывай формулы заново.
    Ловушка: top_k=None и top_p=None означают «не фильтровать», а не
    «оставить ноль кандидатов».
    """
    kept = logits
    # top-k первым: он дешевле (одна сортировка без softmax) и сужает вход
    # для top-p — ровно тот порядок, в котором это делают inference-движки
    if top_k is not None:
        kept = top_k_filter(kept, top_k)
    if top_p is not None:
        kept = top_p_filter(kept, top_p, temperature)
    probs = softmax_with_temperature(kept, temperature)
    return sample_index(probs, rng)
