def rejection_sample(pdf, lo, hi, m, rng, max_tries=10000):
    """Rejection sampling: сэмпл из pdf на [lo, hi] через равномерное предложение.

    pdf — плотность (можно ненормированную), m — её верхняя граница на отрезке,
    то есть pdf(x) <= m для всех x из [lo, hi].
    Алгоритм: предложить x равномерно из [lo, hi], взять u из [0, 1), принять
    x при u * m < pdf(x), иначе пробовать заново.

    rejection_sample(lambda x: 1.0,   0.0, 1.0, 1.0, random.Random(0))  ->  0.8444218
    rejection_sample(lambda x: 2 * x, 0.0, 1.0, 2.0, random.Random(0))  ->  0.8444218
    доля принятых  ->  (площадь под pdf) / (m * (hi - lo))

    Ловушка первая: заниженное m ломает форму — такие x принимаются всегда,
    и распределение получается не то, которое просили.
    Ловушка вторая: если pdf нулевая на всём отрезке, цикл никогда не
    кончится. Ограничь число попыток и брось RuntimeError.
    Ловушка третья: m <= 0 — деление (или сравнение) теряет смысл, ValueError.

    В высокой размерности доля принятых падает экспоненциально — поэтому
    большие модели сэмплируют через MCMC, а не отбраковкой.
    """
